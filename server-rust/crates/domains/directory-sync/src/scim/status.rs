/// HINT `type`, when the whole HINT is a JSON object (Go rejects a malformed HINT).
fn hint_type(hint: Option<&str>) -> Option<String> {
    let value: serde_json::Value = serde_json::from_str(hint?).ok()?;
    match value
        .as_object()?
        .iter()
        .find(|(k, _)| k.eq_ignore_ascii_case("type"))?
        .1
    {
        serde_json::Value::String(s) => Some(s.clone()),
        _ => None,
    }
}

pub fn reducer_status(error: &StatementFailure) -> u16 {
    let Some(code) = error.sqlstate.as_deref() else {
        return 500;
    };
    let kind = hint_type(error.hint.as_deref());
    match code {
        "BZ001" => {
            if kind.as_deref() == Some("over_quota") {
                507
            } else {
                500
            }
        }
        "BZ081" => {
            if kind.as_deref() == Some("bad_outcome") {
                400
            } else {
                404
            }
        }
        "BZ099" => {
            if kind.as_deref() == Some("last_global") {
                409
            } else {
                404
            }
        }
        _ => TABLE
            .iter()
            .find(|(c, _)| *c == code)
            .map_or(500, |(_, status)| *status),
    }
}
