// Command schemagen reflects the typed admin/users DTOs into OpenAPI 3.1
// component schemas and writes them into openapi.yaml between marker comments.
//
// This is the Phase-0B pilot of the typed-DTO → generated-schema mechanism (see
// retired-docs:superpowers/plans/archive/2026-06-20-openapi-coverage-expansion.md). The DTO IS the
// schema: the handler request/response structs in internal/admin are the single
// source of truth, and the spec's `User`/`UserCreate`/`UserUpdate` schemas are
// reflected from them, so the two can never drift. Run it via:
//
//	go generate ./mailserver/api/...
//
// It is idempotent: re-running produces byte-identical output. Only the region
// between `# BEGIN GENERATED SCHEMAS (schemagen)` and `# END GENERATED SCHEMAS`
// in openapi.yaml is rewritten; the hand-authored paths, x-visibility tags, and
// other schemas are left untouched.
package main

import (
	"bytes"
	"fmt"
	"os"
	"path/filepath"
	"reflect"
	"runtime"
	"sort"
	"strings"

	"github.com/getkin/kin-openapi/openapi3"
	"github.com/getkin/kin-openapi/openapi3gen"
	yaml "go.yaml.in/yaml/v3"

	"setjoin.com/mailserver/internal/admin"
)

const (
	beginMarker = "  # BEGIN GENERATED SCHEMAS (schemagen) — do not edit by hand; run `go generate ./mailserver/api/...`"
	endMarker   = "  # END GENERATED SCHEMAS"
)

// pilotSchema binds an OpenAPI component-schema name to the Go DTO it is
// reflected from. The schema name is the public contract ($ref'd from the
// /admin/users paths); the Go type is the source of truth. request marks a
// request-body schema: those get the repo's strict-body posture stamped
// (additionalProperties:false + bounded password) so the published contract
// can never under-specify a privileged mutation surface.
type pilotSchema struct {
	name    string // the OpenAPI components/schemas key (e.g. "User")
	value   any    // a zero value of the DTO to reflect
	request bool   // true for request bodies (strict-body contract stamp)
}

// pilots is the Phase-0B scope: admin/users only. Sorted output is keyed on
// .name, so declaration order here does not affect the generated bytes.
var pilots = []pilotSchema{
	{name: "User", value: admin.UserResponse{}},
	{name: "UserCreate", value: admin.UserCreateRequest{}, request: true},
	{name: "UserUpdate", value: admin.UserUpdateRequest{}, request: true},
}

func main() {
	if err := run(); err != nil {
		fmt.Fprintln(os.Stderr, "schemagen:", err)
		os.Exit(1)
	}
}

func run() error {
	specPath, err := specPath()
	if err != nil {
		return err
	}

	block, err := generateBlock()
	if err != nil {
		return err
	}

	orig, err := os.ReadFile(specPath) //nolint:gosec // G304: specPath is the compiled-in source-relative openapi.yaml (runtime.Caller + fixed join), not user input; this is a build-time codegen tool
	if err != nil {
		return fmt.Errorf("read %s: %w", specPath, err)
	}

	updated, err := replaceBlock(orig, block)
	if err != nil {
		return err
	}

	if bytes.Equal(orig, updated) {
		return nil // already up to date — no write, no churn
	}
	if err := os.WriteFile(specPath, updated, 0o600); err != nil { //nolint:gosec // G703: specPath is the compiled-in source-relative openapi.yaml (runtime.Caller + filepath.Clean of fixed literals), not user input — build-time codegen tool
		return fmt.Errorf("write %s: %w", specPath, err)
	}
	return nil
}

// specPath resolves openapi.yaml relative to THIS source file, so `go generate`
// works regardless of the caller's working directory.
func specPath() (string, error) {
	_, self, _, ok := runtime.Caller(0)
	if !ok {
		return "", fmt.Errorf("cannot resolve schemagen source path")
	}
	// self = .../mailserver/api/cmd/schemagen/main.go → spec is ../../openapi.yaml
	return filepath.Clean(filepath.Join(filepath.Dir(self), "..", "..", "openapi.yaml")), nil
}

// formatCustomizer reads the `openapi:"format=…"` struct tag and stamps the
// OpenAPI `format` onto the field's schema — the one piece of the contract Go's
// type system can't carry (a string is just a string, so `format: email` /
// `format: password` would be lost). This keeps the DTO authoritative while
// preserving the semantic formats the hand-authored spec had.
func formatCustomizer(_ string, _ reflect.Type, tag reflect.StructTag, schema *openapi3.Schema) error {
	for _, opt := range parseOpenAPITag(tag) {
		if f, ok := strings.CutPrefix(opt, "format="); ok {
			schema.Format = f
		}
	}
	return nil
}

// parseOpenAPITag splits the `openapi:"a,b=c"` tag into its comma-separated
// options. Empty when absent.
func parseOpenAPITag(tag reflect.StructTag) []string {
	v := tag.Get("openapi")
	if v == "" {
		return nil
	}
	return strings.Split(v, ",")
}

// requiredFields returns the json field names of t that carry `openapi:"…,required"`,
// in struct-declaration order. schemagen folds these into the schema's Required
// list (kin-openapi does not derive `required` from Go non-pointer-ness), so the
// generated schema keeps the hand-authored contract's required markers.
func requiredFields(t reflect.Type) []string {
	var req []string
	for i := 0; i < t.NumField(); i++ {
		f := t.Field(i)
		isReq := false
		for _, opt := range parseOpenAPITag(f.Tag) {
			if opt == "required" {
				isReq = true
			}
		}
		if !isReq {
			continue
		}
		name := f.Tag.Get("json")
		if comma := strings.IndexByte(name, ','); comma >= 0 {
			name = name[:comma]
		}
		if name == "" || name == "-" {
			name = f.Name
		}
		req = append(req, name)
	}
	return req
}

// generateBlock reflects every pilot DTO into an OpenAPI schema and renders the
// marked YAML region (markers included). The schemas are emitted in name order
// so the output is deterministic.
func generateBlock() (string, error) {
	// UseAllExportedFields drives the reflection purely off the json tags (the
	// wire contract); formatCustomizer stamps the semantic `format` hints from the
	// `openapi:"format=…"` tags. The pilot DTOs are flat scalar structs (no nested
	// component schemas), so each schema is fully inlined under its name.
	gen := openapi3gen.NewGenerator(
		openapi3gen.UseAllExportedFields(),
		openapi3gen.SchemaCustomizer(formatCustomizer),
	)

	named := make([]pilotSchema, len(pilots))
	copy(named, pilots)
	sort.Slice(named, func(i, j int) bool { return named[i].name < named[j].name })

	var body strings.Builder
	for _, p := range named {
		ref, err := gen.NewSchemaRefForValue(p.value, nil)
		if err != nil {
			return "", fmt.Errorf("reflect %s: %w", p.name, err)
		}
		// Fold the `openapi:"…,required"` fields into the schema's required list
		// (sorted, so the output is stable regardless of struct order).
		if req := requiredFields(reflect.TypeOf(p.value)); len(req) > 0 {
			sort.Strings(req)
			ref.Value.Required = req
		}
		if p.request {
			stampStrictRequestBody(ref.Value)
		}
		rendered, err := renderSchema(p.name, ref.Value)
		if err != nil {
			return "", fmt.Errorf("render %s: %w", p.name, err)
		}
		body.WriteString(rendered)
	}

	return beginMarker + "\n" + body.String() + endMarker + "\n", nil
}

// stampStrictRequestBody stamps the repo's strict-body convention onto a
// generated request schema (D-MAILSERVER-API-003): unknown/trailing properties
// are rejected (additionalProperties:false), and a password property carries
// the shared/validate password bounds — minLength 8 is the default policy
// floor (shared/validate/password.go defaultMinPasswordLength), maxLength 72
// the exported bcrypt cross-profile ceiling (validate.PasswordMaxBytes). The
// handler still enforces the live per-deployment policy; the contract now
// states at least the floor every deployment shares.
func stampStrictRequestBody(schema *openapi3.Schema) {
	schema.WithoutAdditionalProperties()
	if pw, ok := schema.Properties["password"]; ok && pw.Value != nil {
		if pw.Value.MinLength == 0 {
			pw.Value.MinLength = 8
		}
		if pw.Value.MaxLength == nil {
			pw.Value.MaxLength = openapi3.Ptr(uint64(72))
		}
	}
}

// renderSchema marshals one schema to YAML and indents it as a child of
// components/schemas: the schema name at 4 spaces, its body at 6. The kin-openapi
// Schema.MarshalYAML emits a clean, key-sorted mapping, which is what makes the
// output stable across runs.
func renderSchema(name string, schema *openapi3.Schema) (string, error) {
	raw, err := yaml.Marshal(schema)
	if err != nil {
		return "", err
	}
	var out strings.Builder
	fmt.Fprintf(&out, "    %s:\n", name)
	for _, line := range strings.Split(strings.TrimRight(string(raw), "\n"), "\n") {
		if line == "" {
			out.WriteString("\n")
			continue
		}
		// Schema body sits two levels under "schemas:" (6-space indent).
		out.WriteString("      ")
		out.WriteString(line)
		out.WriteString("\n")
	}
	return out.String(), nil
}

// replaceBlock swaps the content between the BEGIN/END markers for the freshly
// generated block. The markers MUST already exist in the file (they are added
// once, by hand, where the generated schemas should live); a missing marker is a
// hard error rather than a silent append, so the generated region's location
// stays under human control.
func replaceBlock(orig []byte, block string) ([]byte, error) {
	text := string(orig)
	bi := strings.Index(text, beginMarker)
	if bi < 0 {
		return nil, fmt.Errorf("BEGIN marker not found in openapi.yaml (expected %q)", strings.TrimSpace(beginMarker))
	}
	ei := strings.Index(text, endMarker)
	if ei < 0 {
		return nil, fmt.Errorf("END marker not found in openapi.yaml (expected %q)", strings.TrimSpace(endMarker))
	}
	// Extend ei past the end-marker line (include its trailing newline if present).
	lineEnd := strings.IndexByte(text[ei:], '\n')
	if lineEnd < 0 {
		ei = len(text)
	} else {
		ei += lineEnd + 1
	}
	return []byte(text[:bi] + block + text[ei:]), nil
}
