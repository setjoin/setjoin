CREATE OR REPLACE FUNCTION public.feature_toggle_registry_mode_set(
  p_mode text, p_compiled_digest text, p_actor bigint, p_ip inet, p_reason text
) RETURNS jsonb LANGUAGE plpgsql SECURITY DEFINER
SET search_path = public, pg_temp AS $$
DECLARE
  v_before public.feature_toggle_registry_state%ROWTYPE;
  v_unknown_count bigint;
BEGIN
  IF p_mode NOT IN ('observe','enforce') THEN
    RAISE EXCEPTION 'invalid registry mode' USING ERRCODE='BZ261',
      HINT=jsonb_build_object('type','invalid_registry_mode')::text;
  END IF;
  IF p_reason IS NULL OR btrim(p_reason) = '' OR octet_length(p_reason) > 1024
     OR p_reason ~ '[[:cntrl:]]' THEN
    RAISE EXCEPTION 'invalid audit reason' USING ERRCODE='BZ261',
      HINT=jsonb_build_object('type','invalid_audit_reason')::text;
  END IF;

  PERFORM public.feature_registry_lock();
  SELECT * INTO STRICT v_before FROM public.feature_toggle_registry_state
    WHERE singleton FOR UPDATE;
  IF p_mode = 'enforce' THEN
    IF p_compiled_digest IS DISTINCT FROM v_before.registry_digest THEN
      RAISE EXCEPTION 'feature registry digest mismatch'
        USING ERRCODE='BZ262', HINT=jsonb_build_object(
          'type','feature_registry_skew','installedDigest',v_before.registry_digest,
          'compiledDigest',p_compiled_digest)::text;
    END IF;
    SELECT count(*) INTO v_unknown_count FROM public.feature_toggles
      WHERE public.feature_registry_classify(key) = 'unknown';
    IF v_unknown_count <> 0 THEN
      RAISE EXCEPTION 'unknown feature rows prevent enforcement'
        USING ERRCODE='BZ262', HINT=jsonb_build_object(
          'type','feature_registry_unknown_rows','count',v_unknown_count)::text;
    END IF;
  END IF;

  UPDATE public.feature_toggle_registry_state
    SET mode=p_mode, updated_at=now() WHERE singleton;
  PERFORM public.audit_write(p_actor, 'feature_registry.mode_set', 'feature_toggle_registry', NULL,
    to_jsonb(v_before), jsonb_build_object(
      'mode',p_mode,'registry_digest',v_before.registry_digest),
    p_ip, btrim(p_reason), 'core');
  PERFORM public.app_notify('config_changed', jsonb_build_object(
    'registryMode',p_mode,'reload',true)::text);
  RETURN jsonb_build_object('mode',p_mode,'registryDigest',v_before.registry_digest);
END;
$$;

