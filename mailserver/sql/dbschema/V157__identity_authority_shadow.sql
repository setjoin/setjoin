-- V157: normalized authority/provenance records and the I1 shadow ledger.
--
-- Authority/grant mutation remains disabled until I4. This migration creates
-- the constrained schema and backfills only facts that can be represented
-- without guessing. The shadow ledger is the mechanical rollout gate.

CREATE TABLE public.identity_attribute_authority (
    user_id             BIGINT NOT NULL REFERENCES public.users(id) ON DELETE RESTRICT,
    field               TEXT NOT NULL,
    authority_kind      TEXT NOT NULL,
    source_id           BIGINT REFERENCES public.identity_sources(id) ON DELETE RESTRICT,
    link_id             BIGINT REFERENCES public.user_identity_links(id) ON DELETE RESTRICT,
    precedence          SMALLINT NOT NULL DEFAULT 100 CHECK (precedence BETWEEN 0 AND 1000),
    source_version      TEXT,
    value_digest        BYTEA,
    local_override_state TEXT NOT NULL DEFAULT 'none',
    generation          BIGINT NOT NULL DEFAULT 1 CHECK (generation > 0),
    updated_at          TIMESTAMPTZ NOT NULL DEFAULT now(),
    PRIMARY KEY (user_id, field),
    CONSTRAINT identity_attribute_authority_field_check CHECK (
        field IN (
            'email','display_name','first_name','last_name','job_title',
            'phone','department_id','manager_id','enabled'
        )
    ),
    CONSTRAINT identity_attribute_authority_kind_check CHECK (
        authority_kind IN ('local','source')
    ),
    CONSTRAINT identity_attribute_authority_source_check CHECK (
        (authority_kind = 'local' AND source_id IS NULL AND link_id IS NULL)
        OR (authority_kind = 'source' AND source_id IS NOT NULL AND link_id IS NOT NULL)
    ),
    CONSTRAINT identity_attribute_authority_override_check CHECK (
        local_override_state IN ('none','active','cleared')
    )
);

CREATE INDEX identity_attribute_authority_source_idx
    ON public.identity_attribute_authority (source_id, field)
    WHERE source_id IS NOT NULL;
CREATE INDEX identity_attribute_authority_link_idx
    ON public.identity_attribute_authority (link_id)
    WHERE link_id IS NOT NULL;

CREATE TABLE public.identity_entitlement_grants (
    id                  BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id             BIGINT NOT NULL REFERENCES public.users(id) ON DELETE RESTRICT,
    target_kind         TEXT NOT NULL,
    target_id           BIGINT NOT NULL,
    entitlement_kind    TEXT NOT NULL,
    entitlement_id      BIGINT NOT NULL,
    provenance_kind     TEXT NOT NULL,
    source_id           BIGINT REFERENCES public.identity_sources(id) ON DELETE RESTRICT,
    link_id             BIGINT REFERENCES public.user_identity_links(id) ON DELETE RESTRICT,
    source_object       TEXT,
    generation          BIGINT NOT NULL DEFAULT 1 CHECK (generation > 0),
    granted_by          BIGINT REFERENCES public.users(id) ON DELETE SET NULL,
    valid_from          TIMESTAMPTZ NOT NULL DEFAULT now(),
    valid_until         TIMESTAMPTZ,
    revoked_at          TIMESTAMPTZ,
    created_at          TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at          TIMESTAMPTZ NOT NULL DEFAULT now(),
    CONSTRAINT identity_entitlement_grants_target_check CHECK (
        target_kind IN ('person','mailbox')
        AND target_id > 0
    ),
    CONSTRAINT identity_entitlement_grants_entitlement_check CHECK (
        entitlement_kind IN ('distribution_group','admin_role_group')
        AND entitlement_id > 0
    ),
    CONSTRAINT identity_entitlement_grants_provenance_check CHECK (
        provenance_kind IN ('manual','source','legacy_ambiguous')
    ),
    CONSTRAINT identity_entitlement_grants_source_check CHECK (
        (provenance_kind = 'source'
            AND source_id IS NOT NULL
            AND link_id IS NOT NULL
            AND source_object IS NOT NULL
            AND octet_length(source_object) BETWEEN 1 AND 2048)
        OR (provenance_kind <> 'source'
            AND source_id IS NULL AND link_id IS NULL AND source_object IS NULL)
    ),
    CONSTRAINT identity_entitlement_grants_manual_actor_check CHECK (
        provenance_kind <> 'manual' OR granted_by IS NOT NULL
    ),
    CONSTRAINT identity_entitlement_grants_validity_check CHECK (
        valid_until IS NULL OR valid_until > valid_from
    )
);

CREATE UNIQUE INDEX identity_entitlement_grants_live_provenance_key
    ON public.identity_entitlement_grants (
        user_id, target_kind, target_id, entitlement_kind, entitlement_id,
        provenance_kind, source_id, link_id, source_object
    ) NULLS NOT DISTINCT
    WHERE revoked_at IS NULL;
CREATE INDEX identity_entitlement_grants_user_idx
    ON public.identity_entitlement_grants (user_id, revoked_at, entitlement_kind);
CREATE INDEX identity_entitlement_grants_source_idx
    ON public.identity_entitlement_grants (source_id, generation, revoked_at)
    WHERE source_id IS NOT NULL;
CREATE INDEX identity_entitlement_grants_link_idx
    ON public.identity_entitlement_grants (link_id, revoked_at)
    WHERE link_id IS NOT NULL;

CREATE TABLE public.identity_shadow_divergences (
    id                  BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    source_id           BIGINT REFERENCES public.identity_sources(id) ON DELETE RESTRICT,
    user_id             BIGINT REFERENCES public.users(id) ON DELETE RESTRICT,
    link_id             BIGINT REFERENCES public.user_identity_links(id) ON DELETE RESTRICT,
    divergence_class    TEXT NOT NULL,
    old_outcome_digest  BYTEA NOT NULL,
    new_outcome_digest  BYTEA NOT NULL,
    first_seen_at       TIMESTAMPTZ NOT NULL DEFAULT now(),
    last_seen_at        TIMESTAMPTZ NOT NULL DEFAULT now(),
    seen_count          BIGINT NOT NULL DEFAULT 1 CHECK (seen_count > 0),
    state               TEXT NOT NULL DEFAULT 'open',
    redacted_sample     JSONB NOT NULL DEFAULT '{}'::jsonb,
    explained_by        BIGINT REFERENCES public.users(id) ON DELETE SET NULL,
    explained_at        TIMESTAMPTZ,
    expires_at          TIMESTAMPTZ NOT NULL DEFAULT (now() + interval '30 days'),
    CONSTRAINT identity_shadow_divergences_class_check CHECK (
        divergence_class IN (
            'expected_legacy_ambiguity','person_mismatch','authority_mismatch',
            'access_mismatch','missing_projection'
        )
    ),
    CONSTRAINT identity_shadow_divergences_state_check CHECK (
        state IN ('open','explained','resolved')
    ),
    CONSTRAINT identity_shadow_divergences_sample_check CHECK (
        jsonb_typeof(redacted_sample) = 'object'
        AND octet_length(redacted_sample::text) <= 2048
    ),
    CONSTRAINT identity_shadow_divergences_explained_check CHECK (
        (state = 'explained' AND explained_at IS NOT NULL)
        OR (state <> 'explained' AND explained_at IS NULL AND explained_by IS NULL)
    )
);

CREATE UNIQUE INDEX identity_shadow_divergences_fact_key
    ON public.identity_shadow_divergences (
        source_id, user_id, link_id, divergence_class
    ) NULLS NOT DISTINCT;
CREATE INDEX identity_shadow_divergences_gate_idx
    ON public.identity_shadow_divergences (state, divergence_class, last_seen_at);
CREATE INDEX identity_shadow_divergences_source_idx
    ON public.identity_shadow_divergences (source_id, state, divergence_class);
CREATE INDEX identity_shadow_divergences_expiry_idx
    ON public.identity_shadow_divergences (expires_at)
    WHERE state = 'resolved';

-- A logical legacy-backfill event exists once per link even when a restart
-- revisits the same user.
CREATE UNIQUE INDEX identity_link_events_legacy_backfill_key
    ON public.identity_link_events (link_id, action)
    WHERE action = 'legacy_backfilled' AND link_id IS NOT NULL;

-- I1 authority backfill: a legacy local_only field is local. An ad_managed
-- field is source-owned only when the user has an active AD provisioning link;
-- missing-link rows remain visible to the shadow comparator.
INSERT INTO public.identity_attribute_authority (
    user_id, field, authority_kind, source_id, link_id, local_override_state
)
SELECT fp.user_id, fp.field, 'local', NULL, NULL,
       CASE
           WHEN COALESCE((u.local_overrides -> fp.field)::boolean, false)
               THEN 'active'
           ELSE 'none'
       END
FROM public.field_policy fp
JOIN public.users u ON u.id = fp.user_id
WHERE fp.policy = 'local_only'
  AND fp.field IN (
      'email','display_name','first_name','last_name','job_title',
      'phone','department_id','manager_id','enabled'
  )
  AND NOT EXISTS (SELECT 1 FROM public.guest_accounts g WHERE g.user_id = fp.user_id)
  AND EXISTS (
      SELECT 1 FROM public.mailboxes m
      WHERE m.user_id = fp.user_id AND m.is_primary
  )
ON CONFLICT (user_id, field) DO NOTHING;

INSERT INTO public.identity_attribute_authority (
    user_id, field, authority_kind, source_id, link_id, local_override_state
)
SELECT fp.user_id, fp.field, 'source', l.source_id, l.id,
       CASE
           WHEN COALESCE((u.local_overrides -> fp.field)::boolean, false)
               THEN 'active'
           ELSE 'none'
       END
FROM public.field_policy fp
JOIN public.users u ON u.id = fp.user_id
JOIN public.user_identity_links l
  ON l.user_id = fp.user_id
 AND l.state = 'active'
 AND 'provision' = ANY (l.purposes)
JOIN public.identity_sources s
  ON s.id = l.source_id AND s.source_key = 'legacy:ad'
WHERE fp.policy = 'ad_managed'
  AND fp.field IN (
      'email','display_name','first_name','last_name','job_title',
      'phone','department_id','manager_id','enabled'
  )
ON CONFLICT (user_id, field) DO NOTHING;

