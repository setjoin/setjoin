-- V166: durable, replay-safe operator decisions for identity match candidates.
--
-- The candidate generation remains the source generation that produced the
-- evidence. These columns bind one operator decision to its exact request
-- without storing raw evidence or introducing an address-based identity key.

ALTER TABLE public.identity_match_candidates
    ADD COLUMN decision_idempotency_key UUID,
    ADD COLUMN decision_request_digest BYTEA,
    ADD COLUMN decision_reason TEXT;

ALTER TABLE public.identity_match_candidates
    ADD CONSTRAINT identity_match_candidates_decision_request_check CHECK (
        (
            decision_idempotency_key IS NULL
            AND decision_request_digest IS NULL
            AND decision_reason IS NULL
        )
        OR
        (
            decision_idempotency_key IS NOT NULL
            AND octet_length(decision_request_digest) = 32
            AND octet_length(decision_reason) BETWEEN 1 AND 1024
            AND decision_reason !~ '[[:cntrl:]]'
        )
    );

CREATE UNIQUE INDEX identity_match_candidates_actor_idempotency_key
    ON public.identity_match_candidates (
        decided_by, decision_idempotency_key
    )
    WHERE decision_idempotency_key IS NOT NULL;

-- A candidate can be deferred and decided again later. Preserve every exact
-- request/result so an old ambiguous-timeout replay remains truthful even
-- after a later decision advances the candidate.
CREATE TABLE public.identity_match_decisions (
    id                  BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    candidate_id        UUID NOT NULL
                            REFERENCES public.identity_match_candidates(id)
                            ON DELETE RESTRICT,
    decided_by          BIGINT NOT NULL
                            REFERENCES public.users(id) ON DELETE RESTRICT,
    idempotency_key     UUID NOT NULL,
    request_digest      BYTEA NOT NULL
                            CHECK (octet_length(request_digest) = 32),
    decision            TEXT NOT NULL
                            CHECK (decision IN ('link','create','reject','defer')),
    reason              TEXT NOT NULL CHECK (
                            octet_length(reason) BETWEEN 1 AND 1024
                            AND reason !~ '[[:cntrl:]]'
                        ),
    person_id           BIGINT REFERENCES public.users(id) ON DELETE RESTRICT,
    link_id             BIGINT REFERENCES public.user_identity_links(id)
                            ON DELETE RESTRICT,
    result              JSONB NOT NULL CHECK (jsonb_typeof(result) = 'object'),
    occurred_at         TIMESTAMPTZ NOT NULL DEFAULT statement_timestamp(),
    UNIQUE (decided_by, idempotency_key)
);

CREATE INDEX identity_match_decisions_candidate_time_idx
    ON public.identity_match_decisions (candidate_id, occurred_at DESC, id DESC);

CREATE FUNCTION public.identity_match_decisions_append_only()
RETURNS trigger
LANGUAGE plpgsql
AS $$
BEGIN
    RAISE EXCEPTION 'identity match decisions are append-only'
        USING ERRCODE = 'BZ017',
              HINT = '{"type":"audit_append_only","table":"identity_match_decisions"}';
END;
$$;

CREATE TRIGGER identity_match_decisions_append_only
    BEFORE UPDATE OR DELETE ON public.identity_match_decisions
    FOR EACH ROW EXECUTE FUNCTION public.identity_match_decisions_append_only();

ALTER TABLE public.identity_match_decisions ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.identity_match_decisions FORCE ROW LEVEL SECURITY;
ALTER TABLE public.identity_match_decisions OWNER TO setjoin_owner;
ALTER FUNCTION public.identity_match_decisions_append_only() OWNER TO setjoin_owner;

