-- push_intents: one row per delivered message that should be considered for a
-- push notification. Reliability shape mirrors scheduled_actions (status +
-- attempts + next_attempt_at + last_error). Like scheduled_actions it carries NO
-- RLS: it is read/written ONLY by the BYPASSRLS pushjobs worker (deliver() writes
-- it inside the delivery txn, which already runs privileged). Idempotent per
-- delivered row via UNIQUE (mailbox_id, message_id).
CREATE TABLE IF NOT EXISTS public.push_intents (
    id              bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    mailbox_id      bigint NOT NULL,
    message_id      bigint NOT NULL,
    received_at     timestamptz NOT NULL,   -- messages partition key (id, received_at)
    status          text NOT NULL DEFAULT 'pending',
    attempts        integer NOT NULL DEFAULT 0,
    next_attempt_at timestamptz NOT NULL DEFAULT now(),
    last_error      text,
    created_at      timestamptz NOT NULL DEFAULT now(),
    CONSTRAINT push_intents_status_check CHECK (status = ANY (ARRAY['pending','done','failed'])),
    CONSTRAINT push_intents_uniq UNIQUE (mailbox_id, message_id)
);

-- Claim index: the worker selects pending rows that are due, oldest first.
CREATE INDEX IF NOT EXISTS idx_push_intents_due
    ON public.push_intents (next_attempt_at)
    WHERE status = 'pending';

