-- Constraint triggers run after the set-based backfill so they also protect
-- every later writer.
CREATE FUNCTION public.identity_link_account_class_guard()
RETURNS trigger
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = pg_catalog, public
AS $$
BEGIN
    IF EXISTS (SELECT 1 FROM public.guest_accounts g WHERE g.user_id = NEW.user_id)
       OR NOT EXISTS (
           SELECT 1 FROM public.mailboxes m
           WHERE m.user_id = NEW.user_id AND m.is_primary
       ) THEN
        RAISE EXCEPTION 'account class is excluded from identity links'
            USING ERRCODE = 'BZ239',
                  HINT = '{"type":"identity_account_class_excluded"}';
    END IF;
    RETURN NEW;
END;
$$;
SELECT public.apply_worker_ownership(
    'public.identity_link_account_class_guard()'::regprocedure
);

CREATE TRIGGER user_identity_links_account_class_guard
    BEFORE INSERT OR UPDATE OF user_id ON public.user_identity_links
    FOR EACH ROW EXECUTE FUNCTION public.identity_link_account_class_guard();

CREATE FUNCTION public.identity_link_limit_guard()
RETURNS trigger
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = pg_catalog, public
AS $$
DECLARE
    v_count INTEGER;
BEGIN
    IF NEW.state <> 'active'
       OR NOT ('authenticate' = ANY (NEW.purposes)) THEN
        RETURN NEW;
    END IF;

    PERFORM pg_advisory_xact_lock(
        hashtextextended('identity-person:' || NEW.user_id::text, 0)
    );
    SELECT count(*) INTO v_count
    FROM public.user_identity_links l
    WHERE l.user_id = NEW.user_id
      AND l.state = 'active'
      AND 'authenticate' = ANY (l.purposes)
      AND l.id <> NEW.id;

    IF v_count >= 8 THEN
        RAISE EXCEPTION 'a person may have at most eight active authentication links'
            USING ERRCODE = 'BZ232',
                  HINT = '{"type":"identity_auth_link_limit","limit":8}';
    END IF;
    RETURN NEW;
END;
$$;
SELECT public.apply_worker_ownership(
    'public.identity_link_limit_guard()'::regprocedure
);

