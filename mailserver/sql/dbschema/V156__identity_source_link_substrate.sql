    DEFERRABLE INITIALLY DEFERRED
    FOR EACH ROW EXECUTE FUNCTION public.identity_link_limit_guard();

CREATE FUNCTION public.identity_lifecycle_link_guard()
RETURNS trigger
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = pg_catalog, public
AS $$
DECLARE
    v_link public.user_identity_links%ROWTYPE;
BEGIN
    IF NEW.authority_kind = 'local' THEN
        RETURN NEW;
    END IF;

    PERFORM pg_advisory_xact_lock(
        hashtextextended('identity-person:' || NEW.user_id::text, 0)
    );
    SELECT * INTO v_link
    FROM public.user_identity_links l
    WHERE l.id = NEW.link_id
    FOR UPDATE;

    IF NOT FOUND
       OR v_link.user_id <> NEW.user_id
       OR v_link.state <> 'active'
       OR NOT ('provision' = ANY (v_link.purposes)) THEN
        RAISE EXCEPTION 'lifecycle authority requires an active provisioning link for the same person'
            USING ERRCODE = 'BZ233',
                  HINT = '{"type":"identity_lifecycle_conflict"}';
    END IF;
    RETURN NEW;
END;
$$;
SELECT public.apply_worker_ownership(
    'public.identity_lifecycle_link_guard()'::regprocedure
);

CREATE CONSTRAINT TRIGGER user_lifecycle_authorities_link_guard
    AFTER INSERT OR UPDATE OF user_id, authority_kind, link_id
    ON public.user_lifecycle_authorities
    DEFERRABLE INITIALLY DEFERRED
    FOR EACH ROW EXECUTE FUNCTION public.identity_lifecycle_link_guard();

CREATE FUNCTION public.identity_lifecycle_link_reverse_guard()
RETURNS trigger
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = pg_catalog, public
AS $$
BEGIN
    IF EXISTS (
        SELECT 1
        FROM public.user_lifecycle_authorities a
        WHERE a.link_id = NEW.id
          AND (
              a.user_id <> NEW.user_id
              OR NEW.state <> 'active'
              OR NOT ('provision' = ANY (NEW.purposes))
          )
    ) THEN
        RAISE EXCEPTION 'a lifecycle link must remain active and provisioning-capable'
            USING ERRCODE = 'BZ233',
                  HINT = '{"type":"identity_lifecycle_conflict"}';
    END IF;
    RETURN NEW;
END;
$$;
SELECT public.apply_worker_ownership(
    'public.identity_lifecycle_link_reverse_guard()'::regprocedure
);

CREATE CONSTRAINT TRIGGER user_identity_links_lifecycle_reverse_guard
    AFTER UPDATE OF user_id, purposes, state
    ON public.user_identity_links
    DEFERRABLE INITIALLY DEFERRED
    FOR EACH ROW EXECUTE FUNCTION public.identity_lifecycle_link_reverse_guard();

