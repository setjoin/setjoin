-- V156: Identity Model Modernization I1 source/link substrate.
--
-- This is an expand-only migration. Legacy readers and writers remain
-- authoritative while feature.identity_model_v2 is OFF. The normalized rows
-- are populated only from protocol-defined immutable anchors; email, UPN,
-- display name, and other soft evidence never create a link.

CREATE TABLE public.identity_sources (
    id                  BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    source_key          TEXT NOT NULL UNIQUE,
    display_name        TEXT NOT NULL,
    kind                TEXT NOT NULL,
    capabilities        JSONB NOT NULL,
    state               TEXT NOT NULL DEFAULT 'draft',
    config_envelope     BYTEA,
    config_key_version  BIGINT NOT NULL DEFAULT 1 CHECK (config_key_version > 0),
    mapping_version     BIGINT NOT NULL DEFAULT 1 CHECK (mapping_version > 0),
    generation          BIGINT NOT NULL DEFAULT 1 CHECK (generation > 0),
    committed_cursor    JSONB,
    committed_cursor_digest BYTEA,
    pending_cursor      JSONB,
    pending_cursor_digest BYTEA,
    last_success_at     TIMESTAMPTZ,
    last_failure_at     TIMESTAMPTZ,
    last_error_code     TEXT,
    created_by          BIGINT REFERENCES public.users(id) ON DELETE SET NULL,
    updated_by          BIGINT REFERENCES public.users(id) ON DELETE SET NULL,
    created_at          TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at          TIMESTAMPTZ NOT NULL DEFAULT now(),
    CONSTRAINT identity_sources_key_check CHECK (
        source_key = btrim(source_key)
        AND octet_length(source_key) BETWEEN 1 AND 64
        AND source_key ~ '^[A-Za-z0-9][A-Za-z0-9._:-]*$'
    ),
    CONSTRAINT identity_sources_display_name_check CHECK (
        display_name = btrim(display_name)
        AND octet_length(display_name) BETWEEN 1 AND 128
        AND display_name !~ '[[:cntrl:]]'
    ),
    CONSTRAINT identity_sources_kind_check CHECK (
        kind IN ('local','ad','ldap','scim','saml','oidc')
    ),
    CONSTRAINT identity_sources_state_check CHECK (
        state IN ('draft','active','paused','error','retired')
    ),
    CONSTRAINT identity_sources_capabilities_check CHECK (
        jsonb_typeof(capabilities) = 'object'
        AND capabilities <> '{}'::jsonb
    ),
    CONSTRAINT identity_sources_committed_cursor_pair_check CHECK (
        (committed_cursor IS NULL) = (committed_cursor_digest IS NULL)
    ),
    CONSTRAINT identity_sources_pending_cursor_pair_check CHECK (
        (pending_cursor IS NULL) = (pending_cursor_digest IS NULL)
    ),
    CONSTRAINT identity_sources_error_pair_check CHECK (
        (last_failure_at IS NULL AND last_error_code IS NULL)
        OR (last_failure_at IS NOT NULL AND last_error_code IS NOT NULL)
    )
);

CREATE INDEX identity_sources_kind_state_idx
    ON public.identity_sources (kind, state);
CREATE INDEX identity_sources_health_idx
    ON public.identity_sources (state, last_success_at, last_failure_at);

CREATE FUNCTION public.identity_source_key_immutable()
RETURNS trigger
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = pg_catalog, public
AS $$
BEGIN
    IF NEW.source_key IS DISTINCT FROM OLD.source_key THEN
        RAISE EXCEPTION 'identity source key is immutable'
            USING ERRCODE = 'BZ228',
                  HINT = '{"type":"identity_source_invalid","field":"sourceKey","remediation":"create a new source instead of renaming the stable key"}';
    END IF;
    RETURN NEW;
END;
$$;
SELECT public.apply_worker_ownership(
    'public.identity_source_key_immutable()'::regprocedure
);

CREATE TRIGGER identity_sources_key_immutable
    BEFORE UPDATE OF source_key ON public.identity_sources
    FOR EACH ROW EXECUTE FUNCTION public.identity_source_key_immutable();

CREATE TABLE public.user_identity_links (
    id                  BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id             BIGINT NOT NULL REFERENCES public.users(id) ON DELETE RESTRICT,
    source_id           BIGINT NOT NULL REFERENCES public.identity_sources(id) ON DELETE RESTRICT,
    external_subject    TEXT NOT NULL,
    purposes            TEXT[] NOT NULL,
    state               TEXT NOT NULL DEFAULT 'candidate',
    generation          BIGINT NOT NULL DEFAULT 1 CHECK (generation > 0),
    link_method         TEXT NOT NULL,
    evidence            JSONB NOT NULL DEFAULT '{}'::jsonb,
    first_seen_at       TIMESTAMPTZ NOT NULL DEFAULT now(),
    last_seen_at        TIMESTAMPTZ NOT NULL DEFAULT now(),
    detached_by         BIGINT REFERENCES public.users(id) ON DELETE SET NULL,
    detached_at         TIMESTAMPTZ,
    detached_reason     TEXT,
    created_at          TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at          TIMESTAMPTZ NOT NULL DEFAULT now(),
    CONSTRAINT user_identity_links_source_subject_key
        UNIQUE (source_id, external_subject),
    CONSTRAINT user_identity_links_subject_check CHECK (
        octet_length(external_subject) BETWEEN 1 AND 2048
        AND external_subject !~ '[[:cntrl:]]'
    ),
    CONSTRAINT user_identity_links_purposes_check CHECK (
        purposes IN (
            ARRAY['authenticate']::text[],
            ARRAY['provision']::text[],
            ARRAY['authenticate','provision']::text[],
            ARRAY['provision','authenticate']::text[]
        )
    ),
    CONSTRAINT user_identity_links_state_check CHECK (
        state IN ('candidate','active','suspended','detaching','detached','conflict')
    ),
    CONSTRAINT user_identity_links_method_check CHECK (
        link_method IN ('legacy_backfill','hard_anchor','operator','jit','migration','relink')
    ),
    CONSTRAINT user_identity_links_detached_check CHECK (
        (state = 'detached' AND detached_at IS NOT NULL
            AND detached_reason IS NOT NULL
            AND octet_length(detached_reason) BETWEEN 1 AND 1024)
        OR
        (state <> 'detached' AND detached_at IS NULL
            AND detached_by IS NULL AND detached_reason IS NULL)
    ),
    CONSTRAINT user_identity_links_seen_order_check CHECK (
        last_seen_at >= first_seen_at
    )
);

CREATE INDEX user_identity_links_user_state_idx
    ON public.user_identity_links (user_id, state);
CREATE INDEX user_identity_links_source_state_seen_idx
    ON public.user_identity_links (source_id, state, last_seen_at);
CREATE INDEX user_identity_links_detached_idx
    ON public.user_identity_links (detached_at)
    WHERE detached_at IS NOT NULL;

