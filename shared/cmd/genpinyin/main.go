// Command genpinyin emits V009__cjk_pinyin_seed.sql: one toneless, most-common
// pinyin reading per CJK codepoint, sourced from go-pinyin's Unihan-derived dict.
//
// Run from the shared module directory:
//
//	cd shared && go run ./cmd/genpinyin
//
// The file is written to mailserver/sql/dbschema/V009__cjk_pinyin_seed.sql
// (resolved relative to the repo root, one level above shared/).
package main

import (
	"fmt"
	"os"
	"path/filepath"
	"regexp"
	"strings"

	"github.com/mozillazg/go-pinyin"
)

const outputRelPath = "mailserver/sql/dbschema/V009__cjk_pinyin_seed.sql"

// readingRe is the closed shape of a pinyin reading this codegen will
// interpolate into SQL: the pinned go-pinyin Normal style emits only ASCII
// lowercase letters. Anything else means the dictionary or style drifted, and
// the tool must FAIL rather than interpolate unvalidated dictionary output
// into a SQL literal (codegen-output-injection hardening).
var readingRe = regexp.MustCompile(`^[a-z]+$`)

// validateReading errors unless py is safe to embed as a SQL string literal.
func validateReading(cp int, py string) error {
	if !readingRe.MatchString(py) {
		return fmt.Errorf("U+%04X: reading %q does not match ^[a-z]+$", cp, py)
	}
	return nil
}

func main() {
	a := pinyin.NewArgs()
	a.Style = pinyin.Normal // toneless
	a.Heteronym = false

	var b strings.Builder
	b.WriteString("-- V009__cjk_pinyin_seed.sql — GENERATED by shared/cmd/genpinyin; do not edit by hand.\n")
	b.WriteString("-- Per-character toneless pinyin for CJK Unified Ideographs (U+4E00..U+9FFF).\n")
	b.WriteString("INSERT INTO public.cjk_pinyin (codepoint, pinyin) VALUES\n")

	first := true
	for cp := 0x4E00; cp <= 0x9FFF; cp++ {
		res := pinyin.Pinyin(string(rune(cp)), a)
		if len(res) == 0 || len(res[0]) == 0 || res[0][0] == "" {
			continue // no reading for this codepoint
		}
		py := res[0][0]
		if err := validateReading(cp, py); err != nil {
			// Fail loudly: never emit a generated seed built from an
			// out-of-contract dictionary reading.
			fmt.Fprintf(os.Stderr, "genpinyin: %v; refusing to emit SQL\n", err)
			os.Exit(1)
		}
		if !first {
			b.WriteString(",\n")
		}
		first = false
		fmt.Fprintf(&b, "  (%d, '%s')", cp, py)
	}
	b.WriteString("\nON CONFLICT (codepoint) DO NOTHING;\n\n")
	b.WriteString("INSERT INTO public.schema_migrations (version, applied_at) VALUES (9, now())\n    ON CONFLICT (version) DO NOTHING;\n")

	// Resolve output path: shared/ is one level below repo root.
	sharedDir, err := os.Getwd()
	if err != nil {
		fmt.Fprintf(os.Stderr, "genpinyin: getwd: %v\n", err)
		os.Exit(1)
	}
	repoRoot := filepath.Dir(sharedDir)
	outPath := filepath.Join(repoRoot, outputRelPath)

	if err := os.WriteFile(outPath, []byte(b.String()), 0o644); err != nil {
		fmt.Fprintf(os.Stderr, "genpinyin: write %s: %v\n", outPath, err)
		os.Exit(1)
	}
	fmt.Printf("genpinyin: wrote %s\n", outPath)
}
