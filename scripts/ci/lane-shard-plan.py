#!/usr/bin/env python3
"""Route-aligned deterministic connected-component shard planner for server-rust-lane.

Partitions every runnable test in `lane-list.json` across shards 1..N while keeping every
coverage entry (0..1095) and all of its shared replay test cases together on a single shard,
so coverage profiles never need cross-shard merging.

Usage:
  lane-shard-plan.py --root REPO --lane-list lane-list.json --shard K/N --out-dir DIR
  lane-shard-plan.py --root REPO --lane-list lane-list.json --shards N --validate
"""
import argparse
import contextlib
import hashlib
import importlib.util
import io
import json
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
REGEX_META = re.compile(r"([\\^$.|?*+()\[\]{}/])")
REGEX_CHUNK_SIZE = 200


def load_adequacy_module(root=ROOT):
    path = Path(root) / "scripts/guards/check-gofree-oracle-adequacy.py"
    if not path.is_file():
        path = ROOT / "scripts/guards/check-gofree-oracle-adequacy.py"
    spec = importlib.util.spec_from_file_location("gofree_oracle_adequacy_for_plan", path)
    module = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(module)
    return module


def expected_tests(document):
    """Exact same runnable test set extraction as merge-lane-shards.py."""
    tests = set()
    for binary, suite in document["rust-suites"].items():
        for name, case in suite["testcases"].items():
            if not case.get("ignored") and case.get("filter-match", {}).get("status", "matches") == "matches":
                tests.add((binary, name))
    return tests


def parse_shard(text):
    match = re.fullmatch(r"([1-9][0-9]*)/([1-9][0-9]*)", text or "")
    if not match or int(match.group(1)) > int(match.group(2)):
        raise ValueError(f"--shard takes K/N with 1 <= K <= N; got {text!r}")
    return int(match.group(1)), int(match.group(2))


def entry_key(suite):
    return {
        "listener": suite["listener"],
        "method": suite["method"],
        "path": suite["path"],
        "family": suite["family"],
        "command": suite.get("command", ""),
    }


def escape_nextest_regex(name):
    return REGEX_META.sub(r"\\\1", name)


def build_filter_toml(tests, shard_label):
    """Build a valid nextest --tool-config-file setting [profile.lane] default-filter."""
    by_binary = {}
    for binary_id, test_name in sorted(tests):
        by_binary.setdefault(binary_id, []).append(test_name)
    if not by_binary:
        expr = "none()"
    else:
        clauses = []
        for binary_id, names in sorted(by_binary.items()):
            if "'" in binary_id or any("'" in n for n in names):
                raise ValueError(f"unsupported single quote in nextest identifier for {binary_id}")
            if len(names) <= REGEX_CHUNK_SIZE:
                alt = "|".join(escape_nextest_regex(n) for n in names)
                clauses.append(f"(binary_id(={binary_id}) & test(/^(?:{alt})$/))")
            else:
                chunks = []
                for start in range(0, len(names), REGEX_CHUNK_SIZE):
                    alt = "|".join(escape_nextest_regex(n) for n in names[start:start + REGEX_CHUNK_SIZE])
                    chunks.append(f"test(/^(?:{alt})$/)")
                clauses.append(f"(binary_id(={binary_id}) & ({' | '.join(chunks)}))")
        expr = " |\n".join(clauses)
    return (
        f"# Generated by scripts/ci/lane-shard-plan.py for shard {shard_label}. Do not edit.\n"
        "[profile.lane]\n"
        "default-filter = '''\n"
        f"{expr}\n"
        "'''\n"
    )


def plan_shards(all_tests, coverage_suites, num_shards):
    """Compute deterministic connected-component shard assignments across 0..num_shards-1.

    Returns a dict with:
      - shard_tests: list[set[(binary_id, test_name)]] of length num_shards
      - shard_eids:  list[list[int]] (sorted entry indices) of length num_shards
      - entry_cases: list[list[(binary_id, test_name)]] indexed by eid
      - test_to_eids: dict[(binary_id, test_name), list[int]] (sorted eids)
      - component_count: int
      - max_component_tests: int
    """
    if num_shards < 1:
        raise ValueError(f"num_shards must be >= 1; got {num_shards}")
    if not all_tests:
        raise ValueError("lane-list.json contains zero runnable tests")

    entry_cases = []
    test_to_eids = {}
    missing_cases = []
    for eid, (route_name, suite) in enumerate(coverage_suites):
        cases = []
        for case in suite.get("cases", []):
            replay = case["replay"]
            test_key = (f"{replay['package']}::{replay['target']}", replay["test"])
            cases.append(test_key)
            if test_key not in all_tests:
                missing_cases.append(f"entry {eid} ({route_name}): {test_key[0]}::{test_key[1]}")
            test_to_eids.setdefault(test_key, []).append(eid)
        entry_cases.append(cases)
    if missing_cases:
        preview = "; ".join(missing_cases[:10])
        raise ValueError(f"{len(missing_cases)} coverage replay case(s) absent from lane-list.json: {preview}")

    for eids in test_to_eids.values():
        eids.sort()

    # Build bipartite connected components over ("entry", eid) and ("test", test_key).
    parent = {}

    def find(node):
        parent.setdefault(node, node)
        while parent[node] != node:
            parent[node] = parent[parent[node]]
            node = parent[node]
        return node

    def union(a, b):
        ra, rb = find(a), find(b)
        if ra != rb:
            parent[rb] = ra

    for eid, cases in enumerate(entry_cases):
        e_node = ("entry", eid)
        find(e_node)
        for test_key in cases:
            union(e_node, ("test", test_key))

    comp_eids = {}
    comp_tests = {}
    for eid in range(len(entry_cases)):
        root = find(("entry", eid))
        comp_eids.setdefault(root, []).append(eid)
    for test_key in test_to_eids:
        root = find(("test", test_key))
        comp_tests.setdefault(root, []).append(test_key)

    components = []
    for root, eids in comp_eids.items():
        eids.sort()
        tests = sorted(comp_tests.get(root, ()))
        components.append((eids, tests))
    # Largest component by test count first, tie-break by entry count then min entry_idx.
    components.sort(key=lambda comp: (-len(comp[1]), -len(comp[0]), comp[0][0]))

    shard_tests = [set() for _ in range(num_shards)]
    shard_eids = [[] for _ in range(num_shards)]

    for eids, tests in components:
        target = min(range(num_shards), key=lambda s: (len(shard_tests[s]), len(shard_eids[s]), s))
        shard_eids[target].extend(eids)
        shard_tests[target].update(tests)

    for s in range(num_shards):
        shard_eids[s].sort()

    # Distribute remaining non-coverage tests deterministically by stable sha256 order,
    # balancing total shard test counts via greedy LPT (within +/-1 unless a single component dominates).
    remaining = sorted(
        all_tests - set(test_to_eids.keys()),
        key=lambda item: (hashlib.sha256(f"{item[0]}\0{item[1]}".encode()).hexdigest(), item[0], item[1]),
    )
    for test_key in remaining:
        target = min(range(num_shards), key=lambda s: (len(shard_tests[s]), s))
        shard_tests[target].add(test_key)

    # Self-verify exact partition invariants before returning.
    union_tests = set()
    total_tests = 0
    for s_tests in shard_tests:
        total_tests += len(s_tests)
        union_tests |= s_tests
    if total_tests != len(all_tests) or union_tests != all_tests:
        raise RuntimeError("shard plan test partition invariant violated")

    union_eids = set()
    total_eids = 0
    for s, s_eids in enumerate(shard_eids):
        total_eids += len(s_eids)
        union_eids.update(s_eids)
        for eid in s_eids:
            if not set(entry_cases[eid]).issubset(shard_tests[s]):
                raise RuntimeError(f"coverage entry {eid} split across shards")
    if total_eids != len(coverage_suites) or union_eids != set(range(len(coverage_suites))):
        raise RuntimeError("shard plan coverage entry partition invariant violated")

    return {
        "shard_tests": shard_tests,
        "shard_eids": shard_eids,
        "entry_cases": entry_cases,
        "test_to_eids": test_to_eids,
        "component_count": len(components),
        "max_component_tests": max((len(c[1]) for c in components), default=0),
    }


def write_shard_outputs(out_dir, shard_index, num_shards, plan, coverage_suites, manifest_hash):
    """Write shard-filter.toml, coverage-cases.tsv, and shard-coverage-entries.json for shard k/N."""
    out_dir = Path(out_dir)
    out_dir.mkdir(parents=True, exist_ok=True)
    shard_label = f"{shard_index}/{num_shards}"
    s = shard_index - 1
    s_tests = plan["shard_tests"][s]
    s_eids = plan["shard_eids"][s]
    test_to_eids = plan["test_to_eids"]
    entry_cases = plan["entry_cases"]

    (out_dir / "shard-filter.toml").write_text(build_filter_toml(s_tests, shard_label))

    tsv_lines = []
    for binary_id, test_name in sorted(s_tests):
        eids = test_to_eids.get((binary_id, test_name))
        if eids:
            tsv_lines.append(f"{binary_id}\t{test_name}\t{','.join(str(e) for e in eids)}\n")
    (out_dir / "coverage-cases.tsv").write_text("".join(tsv_lines))

    entries_payload = {
        "version": 1,
        "shard": shard_label,
        "manifest_hash": manifest_hash,
        "entries": [
            {
                "entry_idx": eid,
                "route_name": coverage_suites[eid][0],
                "key": entry_key(coverage_suites[eid][1]),
                "cases": [[b, t] for b, t in entry_cases[eid]],
            }
            for eid in s_eids
        ],
    }
    (out_dir / "shard-coverage-entries.json").write_text(json.dumps(entries_payload, indent=1) + "\n")
    return {
        "shard": shard_label,
        "tests": len(s_tests),
        "coverage_cases": len(tsv_lines),
        "coverage_entries": len(s_eids),
    }


def main(argv=None):
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--root", type=Path, default=ROOT)
    parser.add_argument("--lane-list", type=Path, required=True)
    parser.add_argument("--inventory", type=Path)
    parser.add_argument("--catalog", type=Path)
    parser.add_argument("--shard", metavar="K/N", help="emit plan files for shard K of N")
    parser.add_argument("--shards", type=int, default=8, help="shard count for --validate when --shard is omitted")
    parser.add_argument("--out-dir", type=Path, help="directory to write shard-filter.toml, coverage-cases.tsv, shard-coverage-entries.json")
    parser.add_argument("--validate", action="store_true", help="validate full 1..N partition and print balance summary")
    args = parser.parse_args(argv)

    if args.out_dir is not None and not args.shard:
        parser.error("--out-dir requires --shard K/N")
    if not args.validate and args.out_dir is None:
        parser.error("specify --out-dir (with --shard K/N) and/or --validate")

    if args.shard:
        shard_index, num_shards = parse_shard(args.shard)
    else:
        shard_index, num_shards = None, args.shards

    root = args.root.resolve()
    inventory_path = args.inventory or root / "server/bins/gateway/route-inventory.json"
    catalog_path = args.catalog or root / "server/tests/conformance/route-catalog.json"

    adequacy = load_adequacy_module(root)
    with contextlib.redirect_stdout(io.StringIO()):
        replays, coverage_suites = adequacy.check(
            root, json.loads(inventory_path.read_text()), json.loads(catalog_path.read_text())
        )
    manifest = adequacy.manifest_identity(replays, coverage_suites)
    all_tests = expected_tests(json.loads(args.lane_list.read_text()))
    plan = plan_shards(all_tests, coverage_suites, num_shards)

    if args.out_dir is not None:
        summary = write_shard_outputs(
            args.out_dir, shard_index, num_shards, plan, coverage_suites, manifest["hash"]
        )
        print(
            f"lane-shard-plan: shard {summary['shard']}: {summary['tests']} tests, "
            f"{summary['coverage_entries']} coverage entries, {summary['coverage_cases']} coverage cases"
        )
    if args.validate:
        counts = [len(s) for s in plan["shard_tests"]]
        entry_counts = [len(e) for e in plan["shard_eids"]]
        print(
            f"lane-shard-plan validate OK: {len(all_tests)} tests, {len(coverage_suites)} coverage entries, "
            f"{plan['component_count']} components (max {plan['max_component_tests']} tests) across {num_shards} shards"
        )
        print(f"  tests/shard:   {counts} (min={min(counts)}, max={max(counts)}, spread={max(counts) - min(counts)})")
        print(f"  entries/shard: {entry_counts} (min={min(entry_counts)}, max={max(entry_counts)})")


if __name__ == "__main__":
    try:
        main()
    except (ValueError, KeyError, OSError, RuntimeError) as error:
        sys.exit(str(error))
