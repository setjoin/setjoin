// canonicalJson renders a value with recursively key-sorted object keys so a
// hash over it is independent of serialization order (ER4 aggregate).
function canonicalJson(value) {
  if (Array.isArray(value)) return `[${value.map(canonicalJson).join(',')}]`;
  if (value && typeof value === 'object') {
    return `{${Object.keys(value).sort().map((k) => `${JSON.stringify(k)}:${canonicalJson(value[k])}`).join(',')}}`;
  }
  return JSON.stringify(value);
}

function safeExistingFile(rootDir, rel) {
  if (typeof rel !== 'string' || rel.trim() === '') return { ok: false, why: 'empty path' };
  if (path.isAbsolute(rel) || rel.includes('\\') || rel.includes('/../') || rel.startsWith('../')) {
    return { ok: false, why: 'unsafe path' };
  }
  const abs = path.resolve(rootDir, rel);
  if (!abs.startsWith(`${rootDir}${path.sep}`)) return { ok: false, why: 'escapes repository root' };
  if (!fs.existsSync(abs) || !fs.statSync(abs).isFile()) return { ok: false, why: 'missing' };
  return { ok: true };
}

function citedPathExists(errors, rootDir, rel, where) {
  const res = safeExistingFile(rootDir, rel);
  if (!res.ok) errors.push({ code: 'E_SEC_REM_PATH', message: `${where}: cited path ${rel} — ${res.why}` });
  return res.ok;
}

// Citation strings sometimes embed line refs ("path lines 31-38") or anchors
// ("path#fragment"); reduce to the path part before checking existence.
function citedReferenceExists(errors, rootDir, ref, where) {
  if (typeof ref !== 'string' || !ref.includes('/')) return; // prose labels are not paths
  const withoutAnchor = ref.split('#')[0];
  const withoutLines = withoutAnchor.split(' lines ')[0].trim();
  return citedPathExists(errors, rootDir, withoutLines, where);
}

function parseJsonDoc(errors, key, raw, { allowFalsy = false } = {}) {
  try {
    const parsed = JSON.parse(raw);
    // JSON null/false/0/'' parse cleanly but are not documents: a falsy value
    // here would silently skip the entire ER section that consumes it. The
    // ONE exception is the hash-pinned ER3 transitions artifact, whose falsy
    // body must reach the byte-exact pin and be reported as E_SEC_REM_STALE.
    if (!allowFalsy && (!parsed || typeof parsed !== 'object')) {
      errors.push({ code: 'E_SEC_REM_SCHEMA', message: `${key}: not a JSON document (got ${JSON.stringify(parsed)})` });
      return null;
    }
    return parsed;
  } catch (error) {
    errors.push({ code: 'E_SEC_REM_SCHEMA', message: `${key}: invalid JSON — ${error.message}` });
    return null;
  }
}

function parsePlanBatches(planText, errors) {
  const batches = new Map();
  const re = /^- \*\*(B\d{2}):\*\* (.+)$/gm;
  let m;
  while ((m = re.exec(planText)) !== null) {
    const occs = m[2].match(/occ_[0-9a-f]{24}/g) ?? [];
    if (batches.has(m[1])) errors.push({ code: 'E_SEC_REM_BATCH', message: `plan: duplicate batch ${m[1]}` });
    batches.set(m[1], occs);
  }
  if (batches.size !== 18) {
    errors.push({ code: 'E_SEC_REM_BATCH', message: `plan: expected 18 immutable batches B01-B18, parsed ${batches.size}` });
  }
  for (const [name, occs] of batches) {
    if (occs.length > 8) errors.push({ code: 'E_SEC_REM_BATCH', message: `plan: batch ${name} holds ${occs.length} occurrences (cap 8)` });
  }
  return batches;
}

function recomputeTriageJoin(triageText) {
  const join = new Map(); // occ -> Set(findingId)
  let mappedRows = 0;
  for (const line of triageText.split('\n')) {
    if (!line.trim()) continue;
    let row;
    try {
      row = JSON.parse(line);
    } catch {
      return { error: `triage-ledger.jsonl: invalid JSONL line` };
    }
    const mapping = row.oldLedgerMapping;
    if (!mapping || mapping === 'new') continue;
    mappedRows += 1;
    for (const occ of String(mapping).match(/occ_[0-9a-f]{24}/g) ?? []) {
      if (!join.has(occ)) join.set(occ, new Set());
      join.get(occ).add(row.findingId);
    }
  }
  return { mappedRows, join };
}

