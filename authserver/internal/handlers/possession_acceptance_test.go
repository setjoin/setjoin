// stitchJSON appends top-level string members to a JSON object body the way
// the SPA's finish calls carry their token/operation members alongside the
// authenticator response.
func stitchJSON(base []byte, extra map[string]string) []byte {
	out := strings.TrimSuffix(string(base), "}")
	for k, v := range extra {
		out += `,"` + k + `":"` + v + `"`
	}
	return []byte(out + "}")
}

// waitForLockWaiter polls pg_stat_activity until at least one OTHER session
// is parked on the named lock wait event running a query matching queryLike —
// the OBSERVED database wait state that replaces sleep-based sequencing in
// the overlap tests (r3 acceptance F-iv): a gate is released only after the
// transaction it means to interleave is demonstrably queued on the database.
// The observer runs on a DEDICATED connection (`obs`, acquired before the
// test parks anything): the parked transactions hold the fixture pool's
// connections, so a pool-level poll would starve in Acquire.
func waitForLockWaiter(t *testing.T, obs *pgxpool.Conn, waitEvent, queryLike string) {
	t.Helper()
	deadline := time.Now().Add(10 * time.Second)
	for time.Now().Before(deadline) {
		var n int
		err := obs.QueryRow(context.Background(), `
			SELECT count(*) FROM pg_stat_activity
			 WHERE datname = current_database()
			   AND wait_event_type = 'Lock'
			   AND wait_event = $1
			   AND pid <> pg_backend_pid()
			   AND query ILIKE $2`,
			waitEvent, "%"+queryLike+"%").Scan(&n)
		if err == nil && n > 0 {
			return
		}
		time.Sleep(20 * time.Millisecond)
	}
	t.Fatalf("no session observed waiting %q on query ~%q within 10s", waitEvent, queryLike)
}

