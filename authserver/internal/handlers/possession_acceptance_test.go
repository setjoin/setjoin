	auth2, err := newSoftwareAuthenticator("localhost", "http://localhost:8080")
	if err != nil {
		t.Fatalf("software authenticator 2: %v", err)
	}
	auth2.credID = auth.credID

	userID, claims0 := newPossessionUserWithEmail(t, h, "sameid", false)
	email := claims0.Email
