// TestTOTPProofVsFactorChangeRace is §4.1 (opus r1 finding 3; rewritten r8 —
// the pre-r8 shape drove the "race" sequentially and could never detect it).
// The proof and the factor change are made to genuinely OVERLAP with the
// round-3 advisory-gate/trigger pattern, every ordering pinned by an OBSERVED
// database wait state (no sleeps):
//
//	(i) the disable COMMITS while the proof is parked mid-transaction BEFORE
//	    verification (the proof holds the person fence queue) → the resumed
//	    proof refuses against the committed disable — no grant, TOTP counter
//	    untouched (nothing was evaluated);
//	(ii) the verification completes IN-TRANSACTION (gate trigger parks the
//	    proof at the grant INSERT, after the code evaluated) while the
//	    disable is STARTED and queues BEHIND the proof's users-row fence →
//	    the disable's generation bump kills the just-issued grant;
//	(iii)/(iv) sequential controls: disable-before-proof and
//	    disable-after-proof without overlap, converging identically.
func TestTOTPProofVsFactorChangeRace(t *testing.T) {
	h := newPossessionHarness(t)

	// The fixture keeps a UV passkey alongside the TOTP factor: disabling
	// TOTP must leave the cohort C1 so the proof reaches the §2.3 cycle and
	// is refused by the DISABLED SECRET itself (not by a cohort guard).
	newFixture := func(label string) (int64, *token.Claims) {
		t.Helper()
		userID, claims := newPossessionUser(t, h, label, true)
		seedEnabledTOTP(t, h, userID)
		return userID, claims
	}
	proof := func(claims *token.Claims) *httptest.ResponseRecorder {
		code, err := totp.GenerateCode(removalTestSecret, time.Now())
		if err != nil {
			t.Error(err)
			return httptest.NewRecorder()
		}
		return postPossession(h, "/auth/mfa/possession/totp",
			map[string]any{"operation": "recovery.regenerate", "code": code}, nil, claims)
	}
	// disable is the factor-change competitor: TOTP off + the §1.8
	// generation bump (what the removal path commits).
	disable := func(userID int64) error {
		_, err := h.pool.Exec(context.Background(),
			`UPDATE users SET totp_enabled = FALSE, factor_generation = factor_generation + 1 WHERE id = $1`, userID)
		return err
	}
	// counterState reads the TOTP bookkeeping the §2.3 split pins: an
	// unevaluated proof moves NOTHING.
	counterState := func(t *testing.T, userID int64) (int, *time.Time) {
		t.Helper()
		var attempts int
		var lastUsed *time.Time
		if err := h.pool.QueryRow(context.Background(),
			`SELECT totp_failed_attempts, last_totp_used_at FROM users WHERE id = $1`, userID,
		).Scan(&attempts, &lastUsed); err != nil {
			t.Fatalf("read counter: %v", err)
		}
		return attempts, lastUsed
	}
	assertCounterUnmoved := func(t *testing.T, userID int64, attempts int, lastUsed *time.Time) {
		t.Helper()
		gotAttempts, gotLastUsed := counterState(t, userID)
		if gotAttempts != attempts {
			t.Fatalf("totp_failed_attempts = %d, want %d — an unevaluated proof must not count", gotAttempts, attempts)
		}
		if (gotLastUsed == nil) != (lastUsed == nil) || (gotLastUsed != nil && !gotLastUsed.Equal(*lastUsed)) {
			t.Fatalf("last_totp_used_at = %v, want %v — the replay claim must not move for an unevaluated proof", gotLastUsed, lastUsed)
		}
	}

	t.Run("(i) disable commits while the proof is parked before verification", func(t *testing.T) {
		userID, claims := newFixture("totprace-i")
		attempts, lastUsed := counterState(t, userID)

		// Session-scoped hold on the person-fence advisory key: the proof's
		// PersonFence (pg_advisory_xact_lock on the same key) parks BEFORE
		// the users fence, the cohort read, and the verification.
		const fenceSQL = `SELECT pg_advisory_lock(hashtextextended($1, 0))`
		held, err := h.pool.Acquire(context.Background())
		if err != nil {
			t.Fatal(err)
		}
		defer func() {
			_, _ = held.Exec(context.Background(),
				`SELECT pg_advisory_unlock(hashtextextended($1, 0))`, userID)
			held.Release()
		}()
		if _, err := held.Exec(context.Background(), fenceSQL, "identity-person:"+strconv.FormatInt(userID, 10)); err != nil {
			t.Fatal(err)
		}
		obs, err := h.pool.Acquire(context.Background())
		if err != nil {
			t.Fatal(err)
		}
		defer obs.Release()

		proofDone := make(chan *httptest.ResponseRecorder, 1)
		go func() { proofDone <- proof(claims) }()
		// OBSERVED: the proof is parked on the person fence — mid-flight,
		// pre-verification.
		waitForLockWaiter(t, obs, "advisory", "identity_auth_person_fence")

		// The disable COMMITS while the proof sits parked: from this moment
		// the enabled secret the proof is about to load no longer exists.
		if err := disable(userID); err != nil {
			t.Fatalf("(i) disable: %v", err)
		}
		// Release: the proof resumes into the committed disable.
		if _, err := held.Exec(context.Background(),
			`SELECT pg_advisory_unlock(hashtextextended($1, 0))`, "identity-person:"+strconv.FormatInt(userID, 10)); err != nil {
			t.Fatal(err)
		}
		rr := <-proofDone
		if rr.Code != http.StatusInternalServerError {
			t.Fatalf("(i) proof against a secret disabled mid-flight status = %d body %s, want 500 (fail-closed bookkeeping: nothing left to evaluate)", rr.Code, rr.Body.String())
		}
		if n := countGrantsFor(t, h, userID); n != 0 {
			t.Fatalf("(i) grant minted against a disabled secret: %d rows", n)
		}
		assertCounterUnmoved(t, userID, attempts, lastUsed)
	})

	t.Run("(ii) verification completes in-tx, disable queued behind the fence", func(t *testing.T) {
		userID, claims := newFixture("totprace-ii")
		G := readFactorGeneration(t, h, userID)

		// Gate trigger parks the proof at the grant INSERT — AFTER the §2.3
		// cycle verified the code inside its transaction, BEFORE the commit.
		const gateKey = 918273647
		held, err := h.pool.Acquire(context.Background())
		if err != nil {
			t.Fatal(err)
		}
		defer func() {
			_, _ = held.Exec(context.Background(), `SELECT pg_advisory_unlock($1)`, gateKey)
			held.Release()
		}()
		if _, err := held.Exec(context.Background(), `SELECT pg_advisory_lock($1)`, gateKey); err != nil {
			t.Fatal(err)
		}
		obs, err := h.pool.Acquire(context.Background())
		if err != nil {
			t.Fatal(err)
		}
		defer obs.Release()
		if _, err := h.pool.Exec(context.Background(), `
			CREATE OR REPLACE FUNCTION possession_race_totp_gate() RETURNS trigger AS $fn$
			BEGIN
				PERFORM pg_advisory_lock(918273647);
				PERFORM pg_advisory_unlock(918273647);
				RETURN NEW;
			END $fn$ LANGUAGE plpgsql`); err != nil {
			t.Fatal(err)
		}
		// Idempotent install (a timed-out prior run can leave the gate).
		if _, err := h.pool.Exec(context.Background(),
			`DROP TRIGGER IF EXISTS possession_race_totp_gate ON mfa_reauth_step_ups`); err != nil {
			t.Fatal(err)
		}
		if _, err := h.pool.Exec(context.Background(), `
			CREATE TRIGGER possession_race_totp_gate
			BEFORE INSERT ON mfa_reauth_step_ups
			FOR EACH ROW WHEN (NEW.user_id = `+strconv.FormatInt(userID, 10)+`)
			EXECUTE FUNCTION possession_race_totp_gate()`); err != nil {
			t.Fatal(err)
		}
		t.Cleanup(func() {
			_, _ = h.pool.Exec(context.Background(), `DROP TRIGGER IF EXISTS possession_race_totp_gate ON mfa_reauth_step_ups`)
			_, _ = h.pool.Exec(context.Background(), `DROP FUNCTION IF EXISTS possession_race_totp_gate()`)
		})

		proofDone := make(chan *httptest.ResponseRecorder, 1)
		go func() { proofDone <- proof(claims) }()
		// OBSERVED: the proof is parked at the gated grant INSERT — the code
		// already verified inside its transaction.
		waitForLockWaiter(t, obs, "advisory", "INSERT INTO mfa_reauth_step_ups")

		// START the disable now: the proof's transaction holds the users row
		// fence, so the UPDATE demonstrably queues behind it (started, not
		// committed) before the gate releases.
		disableDone := make(chan error, 1)
		go func() { disableDone <- disable(userID) }()
		waitForLockWaiter(t, obs, "transactionid", "UPDATE users")

		// Release: the proof commits its verified grant at G; the disable
		// then commits its generation bump.
		if _, err := held.Exec(context.Background(), `SELECT pg_advisory_unlock($1)`, gateKey); err != nil {
			t.Fatal(err)
		}
		rr := <-proofDone
		if rr.Code != http.StatusOK {
			t.Fatalf("(ii) proof status = %d body %s, want 200 (the code verified before the disable committed)", rr.Code, rr.Body.String())
		}
		var issuance struct {
			ReauthToken string `json:"reauth_token"`
		}
		_ = json.Unmarshal(rr.Body.Bytes(), &issuance)
		if err := <-disableDone; err != nil {
			t.Fatalf("(ii) disable: %v", err)
		}
		// Resulting state: the just-issued grant EXISTS but is
		// generation-stale — attributable to the bump, not to a missing row.
		var boundGen int
		var userGen int
		if err := h.pool.QueryRow(context.Background(),
			`SELECT (SELECT bound_factor_generation FROM mfa_reauth_step_ups WHERE user_id = $1),
			        (SELECT factor_generation FROM users WHERE id = $1)`, userID,
		).Scan(&boundGen, &userGen); err != nil {
			t.Fatalf("(ii) read grant/generation: %v", err)
		}
		if int64(boundGen) != G || int64(userGen) != G+1 {
			t.Fatalf("(ii) grant bound at %d, user at %d, want bound G=%d vs user G+1=%d (the bump must kill the grant)", boundGen, userGen, G, G+1)
		}
		gr := httptest.NewRequest(http.MethodPost, "/auth/backup-codes/generate", strings.NewReader(`{}`))
		gr.Header.Set("Content-Type", "application/json")
		gr.Header.Set(ReauthTokenHeader, issuance.ReauthToken)
		gr = gr.WithContext(ContextWithUser(gr.Context(), claims))
		crr := httptest.NewRecorder()
		h.GenerateBackupCodes(crr, gr)
		if crr.Code != http.StatusForbidden {
			t.Fatalf("(ii) consumption after the disable status = %d body %s, want 403 (the generation bump killed the grant)", crr.Code, crr.Body.String())
		}
		if n := countGrantsFor(t, h, userID); n != 0 {
			t.Fatalf("(ii) dead grant survived consumption: %d rows, want 0 (mismatch refusal deletes it)", n)
		}
	})

	// Control: the disable commits BEFORE the proof starts — the same
	// refusal as (i) without the overlap (the sequential shape the pre-r8
	// test mistook for the race).
	t.Run("(iii) control: disable commits before the proof starts", func(t *testing.T) {
		userID, claims := newFixture("totprace-iii")
		attempts, lastUsed := counterState(t, userID)
		if err := disable(userID); err != nil {
			t.Fatalf("(iii) disable: %v", err)
		}
		rr := proof(claims)
		if rr.Code != http.StatusInternalServerError {
			t.Fatalf("(iii) proof against a disabled secret status = %d body %s, want 500", rr.Code, rr.Body.String())
		}
		if n := countGrantsFor(t, h, userID); n != 0 {
			t.Fatalf("(iii) grant minted against a disabled secret: %d rows", n)
		}
		assertCounterUnmoved(t, userID, attempts, lastUsed)
	})

	// Control: the disable commits AFTER the proof completed — the grant
	// issued at G is dead at G+1.
	t.Run("(iv) control: disable commits after the proof completes", func(t *testing.T) {
		userID, claims := newFixture("totprace-iv")
		rr := proof(claims)
		if rr.Code != http.StatusOK {
			t.Fatalf("(iv) proof status = %d body %s, want 200", rr.Code, rr.Body.String())
		}
		var issuance struct {
			ReauthToken string `json:"reauth_token"`
		}
		_ = json.Unmarshal(rr.Body.Bytes(), &issuance)
		if err := disable(userID); err != nil {
			t.Fatalf("(iv) disable: %v", err)
		}
		gr := httptest.NewRequest(http.MethodPost, "/auth/backup-codes/generate", strings.NewReader(`{}`))
		gr.Header.Set("Content-Type", "application/json")
		gr.Header.Set(ReauthTokenHeader, issuance.ReauthToken)
		gr = gr.WithContext(ContextWithUser(gr.Context(), claims))
		crr := httptest.NewRecorder()
		h.GenerateBackupCodes(crr, gr)
		if crr.Code != http.StatusForbidden {
			t.Fatalf("(iv) consumption after the disable status = %d body %s, want 403", crr.Code, crr.Body.String())
		}
	})
}

