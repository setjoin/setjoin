// proveViaAssertion drives the real possession begin/finish pair on the wire
// bearer and returns the minted reauth_token with the ADMITTED claims (the
// grant binds {JTI, family} of these) and the proving credential ID.
func proveViaAssertion(t *testing.T, h *AuthHandler, userID int64, email string, auth *softwareAuthenticator, operation, targetRef string) (string, *token.Claims, []byte) {
	t.Helper()
	bearer, err := h.jwt.IssueAccess(userID, email, false)
	if err != nil {
		t.Fatalf("issue bearer: %v", err)
	}
	claims, err := h.jwt.Validate(bearer)
	if err != nil {
		t.Fatalf("validate bearer: %v", err)
	}
	hdrs := map[string]string{"Authorization": "Bearer " + bearer}
	body := map[string]any{"operation": operation}
	if targetRef != "" {
		body["target_ref"] = targetRef
	}
	bb := postPossession(h, "/auth/mfa/possession/webauthn/begin", body, hdrs, nil)
	if bb.Code != http.StatusOK {
		t.Fatalf("begin(%s) status = %d body %s, want 200", operation, bb.Code, bb.Body.String())
	}
	var options struct {
		PublicKey struct {
			Challenge string `json:"challenge"`
		} `json:"publicKey"`
	}
	if err := json.Unmarshal(bb.Body.Bytes(), &options); err != nil || options.PublicKey.Challenge == "" {
		t.Fatalf("begin options %s (%v)", bb.Body.String(), err)
	}
	assertion, err := auth.AssertionResponse(options.PublicKey.Challenge, nil)
	if err != nil {
		t.Fatalf("assertion: %v", err)
	}
	extra := map[string]string{"operation": operation}
	if targetRef != "" {
		extra["target_ref"] = targetRef
	}
	fr := postPossessionFinishHdrs(h, "/auth/mfa/possession/webauthn/finish", assertion, extra, hdrs)
	if fr.Code != http.StatusOK {
		t.Fatalf("finish(%s) status = %d body %s, want 200", operation, fr.Code, fr.Body.String())
	}
	var out struct {
		ReauthToken string `json:"reauth_token"`
	}
	if err := json.Unmarshal(fr.Body.Bytes(), &out); err != nil || out.ReauthToken == "" {
		t.Fatalf("finish body %s (%v)", fr.Body.String(), err)
	}
	return out.ReauthToken, claims, auth.credID
}

// TestProvingFactorRevalidatedAtConsumption is §1.1's full-tuple rule at the
// three gated arms that consumed their grant directly (opus r1 finding 4):
// a grant whose PROVING credential was revoked between proof and consumption
// refuses — the mutation never runs, nothing partial commits, and the wire
// answer is the typed 403 reauth_required.
func TestProvingFactorRevalidatedAtConsumption(t *testing.T) {
	t.Run("native device register refuses on a dead proving credential", func(t *testing.T) {
		h := newPossessionHarness(t)
		auth, err := newSoftwareAuthenticator("localhost", "http://localhost:8080")
		if err != nil {
			t.Fatalf("software authenticator: %v", err)
		}
		userID, email, _ := seedC1UserWithPassword(t, h, "devdead", auth)
		tok, claims, _ := proveViaAssertion(t, h, userID, email, auth, "device.register.native", "")

		revokeCredentialRow(t, h, auth.credID)

		privKey, err := ecdsa.GenerateKey(elliptic.P256(), rand.Reader)
		if err != nil {
			t.Fatalf("generate P-256 key: %v", err)
		}
		validKey := hexEncode(elliptic.Marshal(elliptic.P256(), privKey.X, privKey.Y))
		req := httptest.NewRequest(http.MethodPost, "/auth/device/register",
			strings.NewReader(`{"provider":"apns","push_token":"tok","device_public_key":"`+validKey+`"}`))
		req.Header.Set("Content-Type", "application/json")
		req.Header.Set(ReauthTokenHeader, tok)
		req = req.WithContext(ContextWithUser(req.Context(), claims))
		rr := httptest.NewRecorder()
		h.DeviceRegister(rr, req)
		if rr.Code != http.StatusForbidden {
			t.Fatalf("device register with a dead proving credential status = %d body %s, want 403", rr.Code, rr.Body.String())
		}
		var n int
		if err := h.pool.QueryRow(context.Background(),
			`SELECT count(*) FROM push_devices WHERE user_id = $1`, userID,
		).Scan(&n); err != nil || n != 0 {
			t.Fatalf("device rows = %d (%v), want 0 (the mutation never ran)", n, err)
		}
	})

	t.Run("passkey revoke refuses on a dead proving credential and leaves the target live", func(t *testing.T) {
		h := newPossessionHarness(t)
		auth, err := newSoftwareAuthenticator("localhost", "http://localhost:8080")
		if err != nil {
			t.Fatalf("software authenticator: %v", err)
		}
		userID, email, _ := seedC1UserWithPassword(t, h, "revdead", auth)
		targetBytes := seedUVPasskey(t, h, userID, "", false)
		target := base64.RawURLEncoding.EncodeToString(targetBytes)
		tok, claims, _ := proveViaAssertion(t, h, userID, email, auth, "webauthn.revoke", target)

		// The PROVER dies (not the target) after the proof.
		revokeCredentialRow(t, h, auth.credID)

		del := httptest.NewRequest(http.MethodDelete, "/auth/webauthn/credential/"+target, nil)
		del.SetPathValue("id", target)
		del.Header.Set(ReauthTokenHeader, tok)
		del = del.WithContext(ContextWithUser(del.Context(), claims))
		rr := httptest.NewRecorder()
		h.WebAuthnRevokeCredential(rr, del)
		if rr.Code != http.StatusForbidden {
			t.Fatalf("revoke with a dead proving credential status = %d body %s, want 403", rr.Code, rr.Body.String())
		}
		var revoked bool
		if err := h.pool.QueryRow(context.Background(),
			`SELECT revoked_at IS NOT NULL FROM passkey_credentials WHERE id = $1`, targetBytes,
		).Scan(&revoked); err != nil || revoked {
			t.Fatalf("target was revoked through a dead proof (%v)", err)
		}
		if n := countGrantsFor(t, h, userID); n != 1 {
			t.Fatalf("grant rows = %d after the refusal, want 1 (the tx rolled back)", n)
		}
	})

	t.Run("registration finish refuses on a dead proving credential and persists nothing", func(t *testing.T) {
		h := newRegisterHarness(t)
		auth, err := newSoftwareAuthenticator("localhost", "http://localhost:8080")
		if err != nil {
			t.Fatalf("software authenticator: %v", err)
		}
		userID, email, _ := seedC1UserWithPassword(t, h, "regdead", auth)
		G := readFactorGeneration(t, h, userID)
		tok, claims, _ := proveViaAssertion(t, h, userID, email, auth, "webauthn.register", "")

		revokeCredentialRow(t, h, auth.credID)

		// The registration ceremony binds the still-live grant; the finish
		// then refuses at the proving-factor check.
		challenge, sessCookie := registerBegin(t, h, userID, claims, tok)
		replacement, err := newSoftwareAuthenticator("localhost", "http://localhost:8080")
		if err != nil {
			t.Fatalf("replacement authenticator: %v", err)
		}
		att, err := replacement.AttestationResponse(challenge)
		if err != nil {
			t.Fatalf("attestation: %v", err)
		}
		fr := postRegisterFinish(h, userID, claims.JTI, email, claims.RefreshFamilyID(), sessCookie, att, tok, "")
		if fr.Code != http.StatusForbidden {
			t.Fatalf("registration finish with a dead proving credential status = %d body %s, want 403", fr.Code, fr.Body.String())
		}
		if n := countRegisteredCredentials(t, h, userID); n != 1 {
			t.Fatalf("credentials = %d after the refused finish, want 1 (nothing persisted)", n)
		}
		if gen := readFactorGeneration(t, h, userID); gen != G {
			t.Fatalf("factor_generation = %d after the refusal, want %d (no bump)", gen, G)
		}
	})
}

// TestMalformedAssertionNotCounted pins the machinery-vs-observation split
// (opus r1 finding 4): a finish body that does not PARSE as an assertion is
// a malformed request — 400, the webauthn_uv counter does not move, the
// ceremony survives, no grant. (Parsed-but-wrong assertions remain
// evaluated failures that count.)
func TestMalformedAssertionNotCounted(t *testing.T) {
	h := newPossessionHarness(t)
	auth, err := newSoftwareAuthenticator("localhost", "http://localhost:8080")
	if err != nil {
		t.Fatalf("software authenticator: %v", err)
	}
	userID, email, _ := seedC1UserWithPassword(t, h, "malformed", auth)
	bearer, err := h.jwt.IssueAccess(userID, email, false)
	if err != nil {
		t.Fatalf("issue bearer: %v", err)
	}
	hdrs := map[string]string{"Authorization": "Bearer " + bearer}

	bb := postPossession(h, "/auth/mfa/possession/webauthn/begin",
		map[string]any{"operation": "recovery.regenerate"}, hdrs, nil)
	if bb.Code != http.StatusOK {
		t.Fatalf("begin status = %d body %s, want 200", bb.Code, bb.Body.String())
	}

	// Valid JSON envelope, unparseable assertion fields (invalid base64url).
	garbage := []byte(`{"id":"AAAA","rawId":"AAAA","type":"public-key",` +
		`"response":{"authenticatorData":"!!!!","clientDataJSON":"!!!!","signature":"!!!!"}}`)
	req := httptest.NewRequest(http.MethodPost, "/auth/mfa/possession/webauthn/finish",
		strings.NewReader(string(stitchJSON(garbage, map[string]string{"operation": "recovery.regenerate"}))))
	req.Header.Set("Content-Type", "application/json")
	for k, v := range hdrs {
		req.Header.Set(k, v)
	}
	rr := httptest.NewRecorder()
	h.MFAPossessionWebAuthnFinish(rr, req)
	if rr.Code != http.StatusBadRequest {
		t.Fatalf("malformed assertion status = %d body %s, want 400", rr.Code, rr.Body.String())
	}
	if budget := readWebAuthnBudget(t, h, userID); budget.Attempts != 0 {
		t.Fatalf("webauthn_uv counter = %d after an unparseable body, want 0 (machinery refusal, never evaluated)", budget.Attempts)
	}
	var ceremonies int
	if err := h.pool.QueryRow(context.Background(),
		`SELECT count(*) FROM webauthn_ceremonies WHERE user_id = $1`, userID,
	).Scan(&ceremonies); err != nil || ceremonies != 1 {
		t.Fatalf("ceremony rows = %d (%v), want 1 (the malformed refusal must not consume it)", ceremonies, err)
	}
	if n := countGrantsFor(t, h, userID); n != 0 {
		t.Fatalf("grant rows = %d, want 0", n)
	}
}
