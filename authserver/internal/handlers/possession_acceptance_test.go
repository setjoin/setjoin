// seedC1UserWithPassword seeds an enabled local user with a working password
// and (optionally) a UV passkey from the software authenticator — C1 via the
// credential, no TOTP/push (the enrollment_required posture).
func seedC1UserWithPassword(t *testing.T, h *AuthHandler, label string, auth *softwareAuthenticator) (int64, string, *token.Claims) {
	t.Helper()
	email := fmt.Sprintf("c1boot-%s-%d@example.test", label, time.Now().UnixNano())
	userID := seedLocalUser(t, h.pool, email)
	if _, err := h.pool.Exec(context.Background(),
		`UPDATE users SET password_hash = $2 WHERE id = $1`, userID, mustHash(t, "correct-horse-battery"),
	); err != nil {
		t.Fatalf("seed password: %v", err)
	}
	if auth != nil {
		seedAuthenticatorCredential(t, h, userID, auth, true)
	}
	claims := removalClaims(userID, "c1-jti-"+strconv.FormatInt(userID, 10))
	claims.Email = email
	return userID, email, claims
}

// postPossessionFinish posts a finish body carrying the assertion bytes plus
// string members (operation, mfa_token, reauth_token...).
func postPossessionFinish(h *AuthHandler, path string, assertion []byte, extra map[string]string, claims *token.Claims) *httptest.ResponseRecorder {
	body := stitchJSON(assertion, extra)
	req := httptest.NewRequest(http.MethodPost, path, strings.NewReader(string(body)))
	req.Header.Set("Content-Type", "application/json")
	if claims != nil {
		req = req.WithContext(ContextWithUser(req.Context(), claims))
	}
	rr := httptest.NewRecorder()
	switch path {
	case "/auth/mfa/possession/webauthn/finish":
		h.MFAPossessionWebAuthnFinish(rr, req)
	default:
		panic("unknown path " + path)
	}
	return rr
}

// loginForBootstrap drives the REAL password login and returns the status
// and mfa_token of the response.
func loginForBootstrap(t *testing.T, h *AuthHandler, email, password string) (int, string) {
	t.Helper()
	body, _ := json.Marshal(map[string]string{"email": email, "password": password})
	req := httptest.NewRequest(http.MethodPost, "/auth/login", strings.NewReader(string(body)))
	req.Header.Set("Content-Type", "application/json")
	rr := httptest.NewRecorder()
	h.Login(rr, req)
	var resp struct {
		Status   string `json:"status"`
		MFAToken string `json:"mfa_token"`
	}
	_ = json.Unmarshal(rr.Body.Bytes(), &resp)
	return rr.Code, resp.MFAToken
}

// TestC1BootstrapUVEndToEnd is §4.4 case 7, BOTH halves: (a) password login
// answers enrollment_required with mfa_token T and NO password grant; (b)
// the Mode B begin creates the management-assertion ceremony; (c) the UV
// finish consumes the ceremony and mints the webauthn_uv mfa_pending grant
// bound to SHA-256(T); (d) presenting any OTHER token at enroll/setup
// refuses; (e) replaying the finish refuses (the ceremony is single-use);
// (f)+(g) setup + confirm complete the bootstrap — with the staged secret
// INSTALLED and provable (the r1 defect 3 repair).
func TestC1BootstrapUVEndToEnd(t *testing.T) {
	h := newRegisterHarness(t)
	auth, err := newSoftwareAuthenticator("localhost", "http://localhost:8080")
	if err != nil {
		t.Fatalf("software authenticator: %v", err)
	}
	userID, email, _ := seedC1UserWithPassword(t, h, "e2e", auth)

	// (a) Password login → enrollment_required + mfa_token T; NO grant row.
	code, T := loginForBootstrap(t, h, email, "correct-horse-battery")
	if code != http.StatusForbidden || T == "" {
		t.Fatalf("(a) login status = %d, T present = %v; want 403 enrollment_required with mfa_token", code, T != "")
	}
	var grantRows int
	if err := h.pool.QueryRow(context.Background(),
		`SELECT count(*) FROM mfa_reauth_step_ups WHERE user_id = $1`, userID,
	).Scan(&grantRows); err != nil || grantRows != 0 {
		t.Fatalf("(a) C1 login left %d grant row(s) — password bootstrap must not issue one (%v)", grantRows, err)
	}

	// (b) Mode B begin with T + the bootstrap operation → 200 UV options;
	// ceremony {management_assertion, T's JTI, family NULL}.
	bb := postPossession(h, "/auth/mfa/possession/webauthn/begin",
		map[string]any{"operation": "bootstrap.totp.enroll", "mfa_token": T}, nil, nil)
	if bb.Code != http.StatusOK {
		t.Fatalf("(b) begin status = %d body %s, want 200", bb.Code, bb.Body.String())
	}
	var beginOptions struct {
		PublicKey struct {
			Challenge        string `json:"challenge"`
			UserVerification string `json:"userVerification"`
		} `json:"publicKey"`
	}
	if err := json.Unmarshal(bb.Body.Bytes(), &beginOptions); err != nil || beginOptions.PublicKey.Challenge == "" {
		t.Fatalf("(b) begin options %s (%v)", bb.Body.String(), err)
	}
	if beginOptions.PublicKey.UserVerification != "required" {
		t.Fatalf("(b) userVerification = %q, want required (server-side UV)", beginOptions.PublicKey.UserVerification)
	}
	pendingClaims, err := h.jwt.Validate(T)
	if err != nil {
		t.Fatalf("(b) validate T: %v", err)
	}
	var ceremonyJTI, ceremonyScope string
	var ceremonyFamily *string
	if err := h.pool.QueryRow(context.Background(),
		`SELECT session_jti, token_scope, refresh_family_id FROM webauthn_ceremonies WHERE user_id = $1`, userID,
	).Scan(&ceremonyJTI, &ceremonyScope, &ceremonyFamily); err != nil || ceremonyJTI != pendingClaims.JTI || ceremonyScope != "mfa_pending" || ceremonyFamily != nil {
		t.Fatalf("(b) ceremony = {%q %q %v} (%v), want {T's JTI mfa_pending NULL}", ceremonyJTI, ceremonyScope, ceremonyFamily, err)
	}

	// (c) UV finish with T → {"granted":true}; the webauthn_uv mfa_pending
	// grant bound to SHA-256(T) commits in the same transaction.
	assertion, err := auth.AssertionResponse(beginOptions.PublicKey.Challenge, nil)
	if err != nil {
		t.Fatalf("(c) assertion: %v", err)
	}
	fr := postPossessionFinish(h, "/auth/mfa/possession/webauthn/finish", assertion,
		map[string]string{"operation": "bootstrap.totp.enroll", "mfa_token": T}, nil)
	if fr.Code != http.StatusOK || !strings.Contains(fr.Body.String(), `"granted":true`) {
		t.Fatalf("(c) finish status = %d body %s, want 200 granted", fr.Code, fr.Body.String())
	}
	var proofMethod, grantScope string
	var proving []byte
	var grantTarget *string
	if err := h.pool.QueryRow(context.Background(),
		`SELECT proof_method, token_scope, proving_factor_id, target_ref
		   FROM mfa_reauth_step_ups WHERE user_id = $1`, userID,
	).Scan(&proofMethod, &grantScope, &proving, &grantTarget); err != nil ||
		proofMethod != "webauthn_uv" || grantScope != "mfa_pending" ||
		string(proving) != string(auth.credID) || grantTarget != nil {
		t.Fatalf("(c) grant = {%q %q %x %v} (%v), want the §1.5.1 step-5 UV grant", proofMethod, grantScope, proving, grantTarget, err)
	}

	// (d) Negative half: enroll/setup presenting any OTHER token → the typed
	// 403 (SHA-256 mismatch), and the UV grant survives.
	T2, err := h.jwt.IssueMFAPending(userID, email)
	if err != nil {
		t.Fatalf("(d) mint decoy token: %v", err)
	}
	dr := postEnrollmentJSON(t, "/auth/totp/enroll/setup", map[string]any{"mfa_token": T2}, h.TOTPEnrollmentSetup)
	if dr.Code != http.StatusForbidden || !strings.Contains(dr.Body.String(), ReauthRequiredCode) {
		t.Fatalf("(d) foreign token status = %d body %s, want 403 reauth_required", dr.Code, dr.Body.String())
	}

	// (e) Negative half: replaying (c) refuses — the ceremony row is
	// single-use; at most one grant ever.
	fr2 := postPossessionFinish(h, "/auth/mfa/possession/webauthn/finish", assertion,
		map[string]string{"operation": "bootstrap.totp.enroll", "mfa_token": T}, nil)
	if fr2.Code != http.StatusForbidden {
		t.Fatalf("(e) replay status = %d body %s, want 403", fr2.Code, fr2.Body.String())
	}

	// (f) enroll/setup with T: peek matches SHA-256(T), one-time binding +
	// pending row → enrollment_id E1.
	sr := postEnrollmentJSON(t, "/auth/totp/enroll/setup", map[string]any{"mfa_token": T}, h.TOTPEnrollmentSetup)
	if sr.Code != http.StatusOK {
		t.Fatalf("(f) setup status = %d body %s, want 200", sr.Code, sr.Body.String())
	}
	E1 := enrollmentIDFromBody(t, sr.Body.Bytes())
	var setupBody struct {
		ProvisioningURI string `json:"provisioning_uri"`
	}
	if err := json.Unmarshal(sr.Body.Bytes(), &setupBody); err != nil {
		t.Fatalf("(f) decode setup: %v", err)
	}
	pkey, err := otp.NewKeyFromURL(setupBody.ProvisioningURI)
	if err != nil {
		t.Fatalf("(f) parse provisioning URI: %v", err)
	}
	// (g) enroll/confirm with the staged code → promotion consumes the
	// grant, enables TOTP with the STAGED secret installed, bumps the
	// generation, audits.
	confirmCode, err := totp.GenerateCode(pkey.Secret(), time.Now())
	if err != nil {
		t.Fatalf("(g) code: %v", err)
	}
	cr := postEnrollmentJSON(t, "/auth/totp/enroll/confirm", map[string]any{
		"mfa_token": T, "code": confirmCode, "enrollment_id": E1,
	}, h.TOTPEnrollmentConfirm)
	if cr.Code != http.StatusOK {
		t.Fatalf("(g) confirm status = %d body %s, want 200", cr.Code, cr.Body.String())
	}
	var totpEnabled bool
	var installedSecret string
	var gen int64
	if err := h.pool.QueryRow(context.Background(),
		`SELECT COALESCE(totp_enabled, FALSE),
		        pgp_sym_decrypt(totp_secret_enc::bytea, current_setting('app.encryption_key')),
		        factor_generation
		   FROM users WHERE id = $1`, userID,
	).Scan(&totpEnabled, &installedSecret, &gen); err != nil {
		t.Fatalf("(g) post-confirm state: %v", err)
	}
	if !totpEnabled || installedSecret != pkey.Secret() || gen != 1 {
		t.Fatalf("(g) state = {enabled=%v secret-match=%v gen=%d}, want {true true 1}", totpEnabled, installedSecret == pkey.Secret(), gen)
	}
	if n := countGrantsFor(t, h, userID); n != 0 {
		t.Fatalf("(g) grant rows = %d after confirm, want 0 (consumed)", n)
	}
	if _, err := h.pool.Exec(context.Background(),
		`SELECT pgp_sym_decrypt(totp_secret_enc::bytea, current_setting('app.encryption_key'))
		   FROM users WHERE id = $1`, userID,
	); err != nil {
		t.Fatalf("(g) secret readback: %v", err)
	}
}

// TestFamilyRevocationInvalidatesCeremonies_ScenarioA is §4.4 case 6
// Scenario A: family F's legally-built registration pair dies with the
// narrow family revocation; family F₂'s legal pair completes its
// registration finish through the PUBLIC handler.
func TestFamilyRevocationInvalidatesCeremonies_ScenarioA(t *testing.T) {
	h := newRegisterHarness(t)
	auth, err := newSoftwareAuthenticator("localhost", "http://localhost:8080")
	if err != nil {
		t.Fatalf("software authenticator: %v", err)
	}
	userID, claimsF := newPossessionUserWithEmail(t, h, "famrev", false)
	seedEnabledTOTP(t, h, userID) // C1 via enabled TOTP at generation G
	claimsF.FamilyID = "F"
	claimsF2 := removalClaims(userID, "famrev-jti-2")
	claimsF2.Email = claimsF.Email
	claimsF2.FamilyID = "F2"

	// (a.1) PUBLIC FLOW, family F: TOTP proof → webauthn.register grant G_A.
	proofCode, err := totp.GenerateCode(removalTestSecret, time.Now())
	if err != nil {
		t.Fatalf("totp code: %v", err)
	}
	ir := postPossession(h, "/auth/mfa/possession/totp",
		map[string]any{"operation": "webauthn.register", "code": proofCode}, nil, claimsF)
	if ir.Code != http.StatusOK {
		t.Fatalf("issuance status = %d body %s, want 200", ir.Code, ir.Body.String())
	}
	var issuance struct {
		ReauthToken string `json:"reauth_token"`
	}
	if err := json.Unmarshal(ir.Body.Bytes(), &issuance); err != nil || issuance.ReauthToken == "" {
		t.Fatalf("issuance body %s (%v)", ir.Body.String(), err)
	}

	// (a.2) PUBLIC FLOW, family F: register begin performs G_A's one-time
	// target binding and creates ceremony C_A (presenting G_A's own token).
	challengeA, sessCookieA := registerBegin(t, h, userID, claimsF, issuance.ReauthToken)

	// (a.3) The second family's pair: exactly what a family-F₂ session's own
	// begin would have produced — minted through the provider, then INSERTed
	// with the begin-arm binding already consumed (the §4.4 bounded
	// fixture; a second public begin would delete C_A, §1.4).
	sessJSONB, hashB, challengeB := mintRegistrationPairFixture(t, h, userID)
	if _, err := h.pool.Exec(context.Background(),
		`INSERT INTO mfa_reauth_step_ups
		   (token_hash, user_id, session_jti, operation, target_ref, proof_method,
		    bound_factor_generation, token_scope, refresh_family_id, expires_at)
		 VALUES ($1, $2, 'famrev-jti-2', 'webauthn.register', $3, 'totp',
		         (SELECT factor_generation FROM users WHERE id = $2),
		         'session', 'F2', now() + interval '5 minutes')`,
		sha256SumHex("family-f2-grant-token"), userID, hashB,
	); err != nil {
		t.Fatalf("fixture G_B: %v", err)
	}
	if _, err := h.pool.Exec(context.Background(),
		`INSERT INTO webauthn_ceremonies
		   (challenge_hash, user_id, kind, operation, target_ref, session_jti, token_scope, refresh_family_id, expires_at)
		 VALUES ($1, $2, 'registration', 'webauthn.register', $1, 'famrev-jti-2', 'session', 'F2', now() + interval '5 minutes')`,
		hashB, userID,
	); err != nil {
		t.Fatalf("fixture C_B: %v", err)
	}

	// (a) all four rows live, grouped by family: one pair per family.
	familyGrantCounts := grantCountsByFamily(t, h, userID)
	familyCeremonyCounts := ceremonyCountsByFamily(t, h, userID)
	if familyGrantCounts["F"] != 1 || familyGrantCounts["F2"] != 1 || familyCeremonyCounts["F"] != 1 || familyCeremonyCounts["F2"] != 1 {
		t.Fatalf("(a) setup counts grants=%v ceremonies=%v, want one pair per family", familyGrantCounts, familyCeremonyCounts)
	}

	// (b) the narrow family revocation.
	var revoked int64
	if err := h.pool.QueryRow(context.Background(),
		`SELECT revoke_user_sessions($1, 'family', 'acceptance-scenario-a', NULL, NULL, 'F')`,
		userID,
	).Scan(&revoked); err != nil || revoked == 0 {
		t.Fatalf("(b) revoke_user_sessions = %d (%v), want >0", revoked, err)
	}

	// (c) family-F rows 0; family-F₂ rows still 2 — the deletion matched
	// ONLY refresh_family_id = F.
	familyGrantCounts = grantCountsByFamily(t, h, userID)
	familyCeremonyCounts = ceremonyCountsByFamily(t, h, userID)
	if familyGrantCounts["F"] != 0 || familyCeremonyCounts["F"] != 0 {
		t.Fatalf("(c) family-F rows survived: grants=%v ceremonies=%v", familyGrantCounts, familyCeremonyCounts)
	}
	if familyGrantCounts["F2"] != 1 || familyCeremonyCounts["F2"] != 1 {
		t.Fatalf("(c) family-F₂ rows disturbed: grants=%v ceremonies=%v — the deletion widened", familyGrantCounts, familyCeremonyCounts)
	}

	// (d) family-F finish refuses: C_A and G_A are gone AND the §2.2 durable
	// recheck refuses the revoked family's bearer.
	attA, err := auth.AttestationResponse(challengeA)
	if err != nil {
		t.Fatalf("(d) attestation: %v", err)
	}
	dr := postRegisterFinish(h, userID, claimsF.JTI, claimsF.Email, "F", sessCookieA, attA, issuance.ReauthToken, "")
	if dr.Code != http.StatusForbidden {
		t.Fatalf("(d) family-F finish status = %d body %s, want 403", dr.Code, dr.Body.String())
	}

	// (e) family-F₂ completes: finish C_B and consume G_B through the PUBLIC
	// handler — attestation verified with UV, C_B + G_B consumed together,
	// the credential persisted, generation G → G+1, success audit — one
	// commit.
	attB, err := auth.AttestationResponse(challengeB)
	if err != nil {
		t.Fatalf("(e) attestation B: %v", err)
	}
	er := postRegisterFinish(h, userID, claimsF2.JTI, claimsF2.Email, "F2", cookieValueFor(t, h, sessJSONB), attB, "family-f2-grant-token", "")
	if er.Code != http.StatusCreated {
		t.Fatalf("(e) family-F₂ finish status = %d body %s, want 201", er.Code, er.Body.String())
	}
	if n := countRegisteredCredentials(t, h, userID); n != 1 {
		t.Fatalf("(e) credentials = %d, want the registered one", n)
	}
	if gen := readFactorGeneration(t, h, userID); gen != 1 {
		t.Fatalf("(e) factor_generation = %d, want 1 (G → G+1 at the finish)", gen)
	}
	if n := countRegistrationAudits(t, h, userID); n != 1 {
		t.Fatalf("(e) success audit rows = %d, want 1", n)
	}
	if n := countGrantsFor(t, h, userID); n != 0 {
		t.Fatalf("(e) grant rows = %d after the finish, want 0 (G_B consumed)", n)
	}
}

// registerBegin drives the public WebAuthnRegisterBegin with the GIVEN
// grant token (no fixture seeding) and returns the challenge plus the
// wa_reg_sess cookie value.
func registerBegin(t *testing.T, h *AuthHandler, userID int64, claims *token.Claims, grantToken string) (challenge, sessionCookie string) {
	t.Helper()
	req := httptest.NewRequest(http.MethodGet, "/auth/webauthn/register/begin", nil)
	req.Header.Set(ReauthTokenHeader, grantToken)
	req = req.WithContext(ContextWithUser(req.Context(), claims))
	rr := httptest.NewRecorder()
	h.WebAuthnRegisterBegin(rr, req)
	if rr.Code != http.StatusOK {
		t.Fatalf("register begin: status = %d body %s, want 200", rr.Code, rr.Body.String())
	}
	var options struct {
		PublicKey struct {
			Challenge string `json:"challenge"`
		} `json:"publicKey"`
	}
	if err := json.Unmarshal(rr.Body.Bytes(), &options); err != nil || options.PublicKey.Challenge == "" {
		t.Fatalf("register begin options %s (%v)", rr.Body.String(), err)
	}
	for _, c := range rr.Result().Cookies() {
		if c.Name == "wa_reg_sess" {
			return options.PublicKey.Challenge, c.Value
		}
	}
	t.Fatal("register begin set no wa_reg_sess cookie")
	return "", ""
}

// mintRegistrationPairFixture mints a registration begin through the
// provider (the exact options/session/challenge-hash triple the public begin
// would produce) WITHOUT creating ceremony/grant rows, for the §4.4
// family-F₂ fixture.
func mintRegistrationPairFixture(t *testing.T, h *AuthHandler, userID int64) (sessionJSON, challengeHash string, challenge string) {
	t.Helper()
	passkey := h.passkey.(*authn.PasskeyProvider)
	tx, err := h.pool.Begin(context.Background())
	if err != nil {
		t.Fatal(err)
	}
	defer func() { _ = tx.Rollback(context.Background()) }()
	optJSON, sessJSON, hash, err := passkey.BeginRegistrationCeremony(context.Background(), tx, userID)
	if err != nil {
		t.Fatalf("fixture begin: %v", err)
	}
	var options struct {
		PublicKey struct {
			Challenge string `json:"challenge"`
		} `json:"publicKey"`
	}
	if err := json.Unmarshal(optJSON, &options); err != nil || options.PublicKey.Challenge == "" {
		t.Fatalf("fixture options %s (%v)", optJSON, err)
	}
	return string(sessJSON), hash, options.PublicKey.Challenge
}

