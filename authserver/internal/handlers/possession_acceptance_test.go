	claims := removalClaims(userID, "sameid-jti")
	claims.Email = email
	claims.FamilyID = "F"

	proofStep := 0
	proofCode := func() string {
		t.Helper()
		// Each proof consumes its own 30 s step: the replay claim rejects a
		// reused window.
		code, err := totp.GenerateCode(removalTestSecret, time.Now().Add(time.Duration(proofStep)*31*time.Second))
		proofStep++
		if err != nil {
			t.Fatalf("totp code: %v", err)
		}
		return code
	}

	// (a) proof → webauthn.register grant; begin binds target_ref = hash.
	ir := postPossession(h, "/auth/mfa/possession/totp",
		map[string]any{"operation": "webauthn.register", "code": proofCode()}, nil, claims)
	if ir.Code != http.StatusOK {
		t.Fatalf("(a) proof status = %d body %s", ir.Code, ir.Body.String())
	}
