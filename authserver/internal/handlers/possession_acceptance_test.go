// TestBootstrapGrantIssuedAtomicallyWithScopeToken is §4.2 (opus r1 finding
// 3): the C3 login's mfa_token is only returned when the bootstrap grant row
// committed in the SAME transaction (§1.5.1).
//   - committed case: the grant row holds {SHA-256(mfa_token), the pending
//     JTI, operation bootstrap.totp.enroll, proof_method password, scope
//     mfa_pending, NULL family, NULL target, current generation};
//   - fault case: a fault at the grant INSERT → the login fails closed with
//     NO mfa_token in any response and NO row.
//
// The C1 (passkey-holder) halves of §4.2 TestBootstrapPasskeyHolderRequiresUVProof
// are TestC1BootstrapUVEndToEnd (no password grant; bare-token setup refuses;
// the UV ceremony mints the webauthn_uv grant; setup+confirm complete);
// TestC3PasswordBootstrapEndToEnd below is the C3 contrast half.
func TestBootstrapGrantIssuedAtomicallyWithScopeToken(t *testing.T) {
	h := newPossessionHarness(t)

	// --- committed case ---
	userID, email, _ := seedC1UserWithPassword(t, h, "bootatom", nil) // password only → C3
	code, T := loginForBootstrap(t, h, email, "correct-horse-battery")
	if code != http.StatusForbidden || T == "" {
		t.Fatalf("login status = %d T present = %v, want 403 enrollment_required with mfa_token", code, T != "")
	}
	pendingClaims, err := h.jwt.Validate(T)
	if err != nil {
		t.Fatalf("validate T: %v", err)
	}
	var tokenHash, jti, op, proofMethod, scope string
	var family, target *string
	var boundGen int64
	if err := h.pool.QueryRow(context.Background(),
		`SELECT token_hash, session_jti, operation, proof_method, token_scope,
		        refresh_family_id, target_ref, bound_factor_generation
		   FROM mfa_reauth_step_ups WHERE user_id = $1`, userID,
	).Scan(&tokenHash, &jti, &op, &proofMethod, &scope, &family, &target, &boundGen); err != nil {
		t.Fatalf("bootstrap grant row missing: %v", err)
	}
	var currentGen int64
	_ = h.pool.QueryRow(context.Background(),
		`SELECT factor_generation FROM users WHERE id = $1`, userID).Scan(&currentGen)
	if tokenHash != sha256SumHex(T) || jti != pendingClaims.JTI ||
		op != "bootstrap.totp.enroll" || proofMethod != "password" ||
		scope != "mfa_pending" || family != nil || target != nil || boundGen != currentGen {
		t.Fatalf("grant = {%x %q %q %q %q %v %v %d}, want the §1.5.1 step-5 password bootstrap grant bound to SHA-256(T)",
			tokenHash, jti, op, proofMethod, scope, family, target, boundGen)
	}

	// --- fault case: the grant INSERT fails → no token is ever returned ---
	faultID, faultEmail, _ := seedC1UserWithPassword(t, h, "bootfault", nil)
	seedFaultTrigger(t, h,
		"possession_fault_boot_grant_insert", "fault_grant_insert",
		`CREATE FUNCTION possession_fault_boot_grant_insert() RETURNS trigger AS $fn$
		 BEGIN
		   RAISE EXCEPTION 'injected bootstrap grant failure';
		 END $fn$ LANGUAGE plpgsql`)
	uid := strconv.FormatInt(faultID, 10)
	if _, err := h.pool.Exec(context.Background(), `
		CREATE TRIGGER fault_grant_insert
		BEFORE INSERT ON mfa_reauth_step_ups
		FOR EACH ROW WHEN (NEW.user_id = `+uid+`)
		EXECUTE FUNCTION possession_fault_boot_grant_insert()`); err != nil {
		t.Fatalf("create bootstrap fault trigger: %v", err)
	}
	body, _ := json.Marshal(map[string]string{"email": faultEmail, "password": "correct-horse-battery"})
	req := httptest.NewRequest(http.MethodPost, "/auth/login", strings.NewReader(string(body)))
	req.Header.Set("Content-Type", "application/json")
	rr := httptest.NewRecorder()
	h.Login(rr, req)
	if rr.Code != http.StatusInternalServerError {
		t.Fatalf("faulted bootstrap login status = %d body %s, want 500 (fail-closed)", rr.Code, rr.Body.String())
	}
	if strings.Contains(rr.Body.String(), "mfa_token") {
		t.Fatalf("faulted bootstrap login leaked an mfa_token: %s", rr.Body.String())
	}
	var n int
	if err := h.pool.QueryRow(context.Background(),
		`SELECT count(*) FROM mfa_reauth_step_ups WHERE user_id = $1`, faultID,
	).Scan(&n); err != nil || n != 0 {
		t.Fatalf("faulted bootstrap left %d grant row(s) (%v)", n, err)
	}
}

