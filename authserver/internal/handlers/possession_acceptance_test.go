// TestNormalizedNonUVCredentialCohort is §4.2/§1.2 (r2-named; opus r1
// findings 1+3): a credential classified NOT user-verified never produces a
// user-verified passkey proof.
//   - (a) a non-UV credential alone is cohort C2: the webauthn begin and the
//     possession/totp arm answer the cohort 403 naming the password path;
//   - (b) for a C1 account via TOTP, begin succeeds but the assertion
//     options NEVER advertise the non-UV credential (uv_capable filter);
//   - (c) a UV-flagged assertion signed by that non-UV credential refuses
//     403, records the webauthn_uv counter, issues NO grant;
//   - (d) the failed UV attempt never reclassifies anything (§1.2):
//     uv_capable stays FALSE and a second UV assertion refuses the same way.
func TestNormalizedNonUVCredentialCohort(t *testing.T) {
	h := newPossessionHarness(t)
	auth, err := newSoftwareAuthenticator("localhost", "http://localhost:8080")
	if err != nil {
		t.Fatalf("software authenticator: %v", err)
	}
	userID, email, claims := seedC1UserWithPassword(t, h, "nonuv", nil)
	seedAuthenticatorCredential(t, h, userID, auth, false)
	// Begin/finish admission reads the WIRE (§3.2 T1): present a real
	// non-cnf bearer on both arms; possession/totp admits from the session
	// context.
	bearer, err := h.jwt.IssueAccess(userID, email, false)
	if err != nil {
		t.Fatalf("issue bearer: %v", err)
	}
	hdrs := map[string]string{"Authorization": "Bearer " + bearer}

	// (a) Non-UV credential + no TOTP → C2 password step-up at both arms.
	bb := postPossession(h, "/auth/mfa/possession/webauthn/begin",
		map[string]any{"operation": "recovery.regenerate"}, hdrs, nil)
	if bb.Code != http.StatusForbidden || !strings.Contains(bb.Body.String(), PossessionRequiredCode) {
		t.Fatalf("(a) begin status = %d body %s, want 403 %s", bb.Code, bb.Body.String(), PossessionRequiredCode)
	}
	tr := postPossession(h, "/auth/mfa/possession/totp",
		map[string]any{"operation": "recovery.regenerate", "code": "000000"}, nil, claims)
	if tr.Code != http.StatusForbidden || !strings.Contains(tr.Body.String(), "password_proof_required") {
		t.Fatalf("(a) totp status = %d body %s, want 403 naming the password path", tr.Code, tr.Body.String())
	}

	// (b) C1 via TOTP: begin passes, but the options' allow list must NOT
	// contain the non-UV credential.
	seedEnabledTOTP(t, h, userID)
	bb = postPossession(h, "/auth/mfa/possession/webauthn/begin",
		map[string]any{"operation": "recovery.regenerate"}, hdrs, nil)
	if bb.Code != http.StatusOK {
		t.Fatalf("(b) begin status = %d body %s, want 200", bb.Code, bb.Body.String())
	}
	var options struct {
		PublicKey struct {
			Challenge        string `json:"challenge"`
			AllowCredentials []any  `json:"allowCredentials"`
		} `json:"publicKey"`
	}
	if err := json.Unmarshal(bb.Body.Bytes(), &options); err != nil || options.PublicKey.Challenge == "" {
		t.Fatalf("(b) decode begin options %s (%v)", bb.Body.String(), err)
	}
	if len(options.PublicKey.AllowCredentials) != 0 {
		t.Fatalf("(b) allowCredentials = %d entries, want 0 (the non-UV credential must not be advertised as a proof key)", len(options.PublicKey.AllowCredentials))
	}

	// (c) A UV-flagged assertion signed by the non-UV credential: 403, the
	// webauthn_uv counter records ONE evaluated failure, no grant, and the
	// credential never even entered evaluation (sign count unmoved).
	assertion, err := auth.AssertionResponse(options.PublicKey.Challenge, nil)
	if err != nil {
		t.Fatalf("(c) assertion: %v", err)
	}
	fr := postPossessionFinishHdrs(h, "/auth/mfa/possession/webauthn/finish", assertion,
		map[string]string{"operation": "recovery.regenerate"}, hdrs)
	if fr.Code != http.StatusForbidden {
		t.Fatalf("(c) finish status = %d body %s, want 403 (a non-UV credential can never prove webauthn_uv)", fr.Code, fr.Body.String())
	}
	if budget := readWebAuthnBudget(t, h, userID); budget.Attempts != 1 || budget.LockedUntil != nil {
		t.Fatalf("(c) webauthn_uv counter = {%d %v}, want {1 <nil>} (evaluated failure recorded)", budget.Attempts, budget.LockedUntil)
	}
	if n := countGrantsFor(t, h, userID); n != 0 {
		t.Fatalf("(c) grant rows = %d, want 0 (no grant from a non-UV credential)", n)
	}
	var signCount int
	if err := h.pool.QueryRow(context.Background(),
		`SELECT sign_count FROM passkey_credentials WHERE id = $1`, auth.credID,
	).Scan(&signCount); err != nil || signCount != 0 {
		t.Fatalf("(c) sign_count = %d (%v), want 0 (the credential was filtered, never evaluated)", signCount, err)
	}

	// (d) §1.2: the failed UV attempt never reclassifies — uv_capable stays
	// FALSE and a second UV assertion refuses identically.
	if readCredentialUVCapable(t, h, auth.credID) {
		t.Fatal("(d) a failed UV attempt reclassified the credential to uv_capable")
	}
	assertion2, err := auth.AssertionResponse(options.PublicKey.Challenge, nil)
	if err != nil {
		t.Fatalf("(d) second assertion: %v", err)
	}
	fr2 := postPossessionFinishHdrs(h, "/auth/mfa/possession/webauthn/finish", assertion2,
		map[string]string{"operation": "recovery.regenerate"}, hdrs)
	if fr2.Code != http.StatusForbidden {
		t.Fatalf("(d) second finish status = %d body %s, want 403", fr2.Code, fr2.Body.String())
	}
	if budget := readWebAuthnBudget(t, h, userID); budget.Attempts != 2 {
		t.Fatalf("(d) webauthn_uv counter = %d, want 2", budget.Attempts)
	}
}

